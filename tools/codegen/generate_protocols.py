def validate_public_descriptor_boundary(pool: descriptor_pool.DescriptorPool) -> None:
    """Enforce the public-safe Protobuf module as a fail-closed boundary."""
    public_file = pool.FindFileByName("proto/mindclade/api/v1/mindclade_service.proto")
    dependencies = {dependency.name for dependency in public_file.dependencies}
    unexpected_dependencies = dependencies - PUBLIC_PROTO_DEPENDENCY_ALLOWLIST
    if unexpected_dependencies:
        raise ValueError(
            "public API descriptor imports a non-allowlisted dependency: "
            + ", ".join(sorted(unexpected_dependencies))
        )

    pending = list(public_file.message_types_by_name.values())
    messages: dict[str, protobuf_descriptor.Descriptor] = {}
    while pending:
        message = pending.pop()
        pending.extend(message.nested_types)
        if message.GetOptions().map_entry:
            continue
        local_name = message.full_name.removeprefix("mindclade.api.v1.")
        messages[local_name] = message

    unexpected_messages = set(messages) - set(PUBLIC_PROTO_FIELD_ALLOWLIST)
    missing_messages = set(PUBLIC_PROTO_FIELD_ALLOWLIST) - set(messages)
    if unexpected_messages or missing_messages:
        raise ValueError(
            "public API message allowlist drift: "
            f"unexpected={sorted(unexpected_messages)} missing={sorted(missing_messages)}"
        )

    for local_name, message in messages.items():
        expected_fields = PUBLIC_PROTO_FIELD_ALLOWLIST[local_name]
        actual_fields = {field.name for field in message.fields}
        unexpected_fields = actual_fields - expected_fields
        missing_fields = expected_fields - actual_fields
        if unexpected_fields:
            field_name = sorted(unexpected_fields)[0]
            raise ValueError(
                "public API exposes forbidden field outside its positive allowlist: "
                f"{message.full_name}.{field_name}"
            )
        if missing_fields:
            raise ValueError(
                f"public API field allowlist for {message.full_name} references missing fields "
                f"{sorted(missing_fields)}"
            )
        for field in message.fields:
            if (
                field.message_type is not None
                and field.message_type.full_name == "google.protobuf.Any"
            ):
                raise ValueError(f"public API exposes unrestricted Any at {field.full_name}")
            if field.message_type is not None and not (
                field.message_type.full_name.startswith("mindclade.api.v1.")
                or field.message_type.full_name
                in {"google.protobuf.Timestamp", "google.protobuf.Duration"}
                or field.message_type.GetOptions().map_entry
            ):
                raise ValueError(
                    "public API message closure escapes its hard module boundary at "
                    f"{field.full_name}: {field.message_type.full_name}"
                )

    service = pool.FindServiceByName("mindclade.api.v1.MindcladeService")
    for method in service.methods:
        if not method.input_type.full_name.startswith(
            "mindclade.api.v1."
        ) or not method.output_type.full_name.startswith("mindclade.api.v1."):
            raise ValueError(f"public RPC {method.full_name} escapes the public message boundary")
        if method.client_streaming:
            raise ValueError(f"public RPC {method.full_name} uses unapproved client streaming")


def expand_google_http_path(path_template: str) -> tuple[str, list[str]]:
    """Expand a Google resource-pattern binding into a concrete OpenAPI path."""
    parameter_names: list[str] = []

    def singular(resource: str) -> str:
        if resource.endswith("ies"):
            return resource[:-3] + "y"
        if resource.endswith("s"):
            return resource[:-1]
        return resource

    def replace(match: re.Match[str]) -> str:
        pattern = match.group(2).split("/")
        result: list[str] = []
        index = 0
        while index < len(pattern):
            part = pattern[index]
            if index + 1 < len(pattern) and pattern[index + 1] in {"*", "**"}:
                name = singular(part)
                if name in parameter_names:
                    raise ValueError(f"duplicate expanded path parameter: {name}")
                parameter_names.append(name)
                result.extend([part, "{" + name + "}"])
                index += 2
                continue
            if part in {"*", "**"}:
                raise ValueError(f"unbound wildcard in public HTTP path: {path_template}")
            result.append(part)
            index += 1
        return "/".join(result)

    expanded = re.sub(r"\{([^={}]+)=([^{}]+)\}", replace, path_template)
    if "*" in expanded or re.search(r"\{[^{}=]+=", expanded):
        raise ValueError(f"unsupported public HTTP path template: {path_template}")
    return expanded, parameter_names


PUBLIC_OPERATION_KIND_BY_STREAM = {
    "STREAM_PROJECTION_NONE": "unary",
    "STREAM_PROJECTION_BINARY": "server-stream",
    "STREAM_PROJECTION_SSE": "sse",
}
PUBLIC_OPERATION_MEDIA_TYPE = {
    "unary": "application/json",
    "server-stream": "application/octet-stream",
    "sse": "text/event-stream",
}
PUBLIC_SSE_METHOD = "mindclade.api.v1.MindcladeService.WatchOperation"
PUBLIC_SSE_REQUEST_MODEL = "mindclade.api.v1.WatchOperationRequest"
PUBLIC_SSE_EVENT_MODEL = "mindclade.api.v1.OperationEvent"
PUBLIC_SSE_ERROR_MODEL = "mindclade.api.v1.PublicError"
PUBLIC_SSE_ERROR_EVENT_TYPE = "error"
PUBLIC_SSE_PATH_TEMPLATE = "/v1/{name=tenants/*/projects/*/operations/*}:watch"
PUBLIC_SSE_RESUME_HEADER = "Last-Event-ID"
PUBLIC_SSE_RESPONSE_HEADERS = frozenset({"Cache-Control", "X-Accel-Buffering"})
PUBLIC_SSE_NON_SUCCESS_STATUS = frozenset({400, 401, 403, 404, 410, 412, 500})
OPENAPI_HTTP_METHODS = frozenset({"delete", "get", "patch", "post", "put"})


def public_operation_stream_metadata(
    method: protobuf_descriptor.MethodDescriptor,
    contract: _PublicHTTPContract,
    *,
    http_body: str,
    http_method: str,
    http_path_template: str,
    stream_projection: str,
) -> tuple[str, dict[str, Any] | None]:
    """Validate one public stream binding and return descriptor-owned metadata."""
    if method.client_streaming:
        raise ValueError(f"public HTTP RPC uses unapproved client streaming: {method.full_name}")
    operation_kind = PUBLIC_OPERATION_KIND_BY_STREAM.get(stream_projection)
    if operation_kind is None:
        raise ValueError(f"public RPC has an unspecified stream projection: {method.full_name}")
    expects_server_stream = operation_kind in {"server-stream", "sse"}
    if method.server_streaming != expects_server_stream:
        raise ValueError(
            "public RPC stream projection/server-streaming mismatch: "
            f"{method.full_name} declares {stream_projection}"
        )

    has_sse_policy = cast(protobuf_message.Message, contract).HasField("sse")
    if operation_kind != "sse":
        if has_sse_policy:
            raise ValueError(f"non-SSE public RPC declares an SSE policy: {method.full_name}")
        return operation_kind, None

    if (
        method.full_name != PUBLIC_SSE_METHOD
        or method.input_type.full_name != PUBLIC_SSE_REQUEST_MODEL
        or method.output_type.full_name != PUBLIC_SSE_EVENT_MODEL
    ):
        raise ValueError(
            "unsupported public SSE binding; only "
            f"{PUBLIC_SSE_METHOD}: {PUBLIC_SSE_REQUEST_MODEL} -> "
            f"{PUBLIC_SSE_EVENT_MODEL} is approved"
        )
    error_field = method.output_type.fields_by_name.get("error")
    if (
        error_field is None
        or error_field.number != 9
        or error_field.message_type is None
        or error_field.message_type.full_name != PUBLIC_SSE_ERROR_MODEL
    ):
        raise ValueError(
            "public SSE event model must expose descriptor-owned PublicError field: "
            f"{method.full_name}"
        )
    if http_method != "GET":
        raise ValueError(f"public SSE RPC must use GET: {method.full_name}")
    if http_path_template != PUBLIC_SSE_PATH_TEMPLATE:
        raise ValueError(f"public SSE RPC has an unsupported route: {method.full_name}")
    if http_body or contract.request_body_required:
        raise ValueError(f"public SSE RPC must not declare a request body: {method.full_name}")
    resume_headers = [
        header
        for header in contract.request_headers
        if header.casefold() == PUBLIC_SSE_RESUME_HEADER.casefold()
    ]
    if len(contract.request_headers) != 1 or len(resume_headers) != 1:
        raise ValueError(
            "public SSE RPC must declare exactly one "
            f"{PUBLIC_SSE_RESUME_HEADER} header: {method.full_name}"
        )
    if contract.required_request_headers:
        raise ValueError(f"public SSE request headers must remain optional: {method.full_name}")
    if not contract.bearer_auth:
        raise ValueError(f"public SSE RPC must require bearer authentication: {method.full_name}")
    if list(contract.success_status) != [200]:
        raise ValueError(f"public SSE RPC must declare only HTTP 200 success: {method.full_name}")
    if len(contract.non_success_status) != len(PUBLIC_SSE_NON_SUCCESS_STATUS) or set(
        contract.non_success_status
    ) != set(PUBLIC_SSE_NON_SUCCESS_STATUS):
        raise ValueError(
            "public SSE RPC must declare the exact pre-commit failure status set: "
            f"{method.full_name}"
        )
    response_headers = {header.casefold() for header in contract.response_headers}
    expected_response_headers = {header.casefold() for header in PUBLIC_SSE_RESPONSE_HEADERS}
    if (
        len(contract.response_headers) != len(PUBLIC_SSE_RESPONSE_HEADERS)
        or response_headers != expected_response_headers
    ):
        raise ValueError(
            "public SSE RPC must declare Cache-Control and X-Accel-Buffering responses: "
            f"{method.full_name}"
        )
    if not has_sse_policy:
        raise ValueError(f"public SSE RPC has no SSE policy: {method.full_name}")

    sse = contract.sse
    if sse.retry_milliseconds <= 0:
        raise ValueError(f"public SSE retry interval must be positive: {method.full_name}")
    if sse.heartbeat_interval_seconds <= 0:
        raise ValueError(f"public SSE heartbeat interval must be positive: {method.full_name}")
    for field_name in (
        "heartbeat_reuses_last_durable_event_id",
        "replay_acknowledged_terminal_event",
    ):
        if not cast(protobuf_message.Message, sse).HasField(field_name):
            raise ValueError(
                f"public SSE policy must explicitly set {field_name}: {method.full_name}"
            )
    if not sse.heartbeat_reuses_last_durable_event_id:
        raise ValueError(
            f"public SSE heartbeat must reuse the last durable event ID: {method.full_name}"
        )
    if sse.replay_acknowledged_terminal_event:
        raise ValueError(
            f"public SSE must not replay an acknowledged terminal event: {method.full_name}"
        )

    return operation_kind, {
        "errorEventType": PUBLIC_SSE_ERROR_EVENT_TYPE,
        "eventModel": method.output_type.full_name,
        "resumeHeader": PUBLIC_SSE_RESUME_HEADER,
        "retryMilliseconds": sse.retry_milliseconds,
        "heartbeatIntervalSeconds": sse.heartbeat_interval_seconds,
        "heartbeatReusesLastDurableEventId": sse.heartbeat_reuses_last_durable_event_id,
        "replayAcknowledgedTerminalEvent": sse.replay_acknowledged_terminal_event,
    }


def raw_openapi_document(
    operations: Sequence[Mapping[str, Any]],
    components: Mapping[str, Mapping[str, Any]],
    descriptor_digest: str,
) -> dict[str, Any]:
    """Render a valid descriptor-derived OpenAPI 3.1 document."""
    paths: dict[str, dict[str, Any]] = {}
    for contract in operations:
        path, path_parameters = expand_google_http_path(cast(str, contract["pathTemplate"]))
        parameters: list[dict[str, Any]] = [
            {
                "in": "path",
                "name": name,
                "required": True,
                "schema": {"type": "string"},
            }
            for name in path_parameters
        ]
        required_headers = set(cast(list[str], contract["requiredRequestHeaders"]))
        parameters.extend(
            {
                "in": "header",
                "name": name,
                "required": name in required_headers,
                "schema": {"type": "string"},
            }
            for name in cast(list[str], contract["requestHeaders"])
        )
        parameters.extend(
            {
                "in": "query",
                "name": name,
                "required": False,
                "schema": schema,
            }
            for name, schema in cast(dict[str, dict[str, Any]], contract["queryFields"]).items()
        )
        responses: dict[str, Any] = {}
        success_status = set(cast(list[int], contract["successStatus"]))
        for status_code in cast(list[int], contract["responseStatus"]):
            response: dict[str, Any] = {"description": "Descriptor-derived response contract."}
            if status_code in success_status:
                response["headers"] = {
                    header: {"schema": {"type": "string"}}
                    for header in cast(list[str], contract["responseHeaders"])
                }
                operation_kind = cast(str, contract["operationKind"])
                try:
                    media_type = PUBLIC_OPERATION_MEDIA_TYPE[operation_kind]
                except KeyError as error:
                    raise ValueError(f"unknown public operation kind: {operation_kind}") from error
                response["content"] = {
                    media_type: {
                        "schema": {
                            "$ref": "#/components/schemas/" + cast(str, contract["responseMessage"])
                        }
                    }
                }
            elif status_code != 304:
                response["content"] = {
                    "application/problem+json": {
                        "schema": {"$ref": "#/components/schemas/mindclade.api.v1.PublicError"}
                    }
                }
            responses[str(status_code)] = response
        operation: dict[str, Any] = {
            "operationId": contract["operationId"],
            "parameters": parameters,
            "responses": responses,
            "security": [{"bearerAuth": []}] if contract["auth"] == "bearer" else [],
            "x-mindclade-operation-kind": contract["operationKind"],
        }
        sse = contract.get("sse")
        if contract["operationKind"] == "sse":
            if not isinstance(sse, dict):
                raise ValueError(
                    f"SSE operation has no descriptor policy: {contract['operationId']}"
                )
            operation["x-mindclade-sse"] = cast(dict[str, Any], sse).copy()
        elif sse is not None:
            raise ValueError(
                f"non-SSE operation has descriptor SSE policy: {contract['operationId']}"
            )
        body_message = contract.get("bodyMessage")
        if isinstance(body_message, str):
            operation["requestBody"] = {
                "content": {
                    "application/json": {"schema": {"$ref": "#/components/schemas/" + body_message}}
                },
                "required": contract["requestBodyRequired"],
            }
        paths.setdefault(path, {})[cast(str, contract["method"]).lower()] = operation
    return {
        "openapi": "3.1.0",
        "info": {
            "title": "Mindclade descriptor-derived public API projection",
            "version": "v1-candidate",
        },
        "paths": paths,
        "components": {
            "schemas": dict(components),
            "securitySchemes": {
                "bearerAuth": {"scheme": "bearer", "type": "http"},
            },
        },
        "x-mindclade-binding-contracts": list(operations),
        "x-mindclade-descriptor-digest": descriptor_digest,
        "x-mindclade-schema-version": "mindclade.raw-openapi-projection/v4",
        "x-mindclade-generator": {
            "name": GENERATOR,
            "source": "tools/codegen/generate_protocols.py",
        },
    }


def public_openapi_projection(descriptor_set: bytes) -> dict[str, Any]:
    """Extract raw HTTP bindings and ProtoJSON components from descriptors."""
    files = descriptor_pb2.FileDescriptorSet.FromString(descriptor_set)
    pool = descriptor_pool.DescriptorPool()
    pending = list(files.file)
    while pending:
        progress = False
        for file_descriptor in pending[:]:
            try:
                pool.Add(file_descriptor)
            except Exception:  # Dependencies may not have been installed yet.
                continue
            pending.remove(file_descriptor)
            progress = True
        if not progress:
            missing = ", ".join(sorted(item.name for item in pending))
            raise ValueError(f"cannot resolve public descriptor closure: {missing}")

    validate_public_descriptor_boundary(pool)

    options_class = message_factory.GetMessageClass(
        pool.FindMessageTypeByName("google.protobuf.MethodOptions")
    )
    http_extension = pool.FindExtensionByName("google.api.http")
    contract_extension = pool.FindExtensionByName("mindclade.api.v1.public_http")
    service = pool.FindServiceByName("mindclade.api.v1.MindcladeService")
    operations: list[dict[str, Any]] = []
    for method in service.methods:
        options = options_class.FromString(method.GetOptions().SerializeToString())
        extension_values = cast(Any, options.Extensions)
        rule = cast(_GoogleHTTPRule, extension_values[http_extension])
        contract = cast(_PublicHTTPContract, extension_values[contract_extension])
        verb = cast(protobuf_message.Message, rule).WhichOneof("pattern")
        if verb is None:
            raise ValueError(f"public RPC has no google.api.http binding: {method.full_name}")
        contract_message = contract_extension.message_type
        if contract_message is None:
            raise ValueError("public HTTP extension has no message descriptor")
        stream_field = contract_message.fields_by_name.get("stream")
        if stream_field is None or stream_field.enum_type is None:
            raise ValueError("public HTTP stream contract has no enum descriptor")
        stream_value = stream_field.enum_type.values_by_number.get(contract.stream)
        if stream_value is None:
            raise ValueError(f"public RPC has an unknown stream projection: {method.full_name}")
        raw_path_template: object = getattr(rule, verb)
        if not isinstance(raw_path_template, str):
            raise ValueError(f"public RPC has an invalid HTTP path: {method.full_name}")
        path_template = raw_path_template
        operation_kind, sse = public_operation_stream_metadata(
            method,
            contract,
            http_body=rule.body,
            http_method=verb.upper(),
            http_path_template=path_template,
            stream_projection=stream_value.name,
        )
        path_fields = sorted(
            {value.split(".", 1)[0] for value in re.findall(r"\{([^={}]+)=", path_template)}
        )
        body = rule.body
        body_field = method.input_type.fields_by_name.get(body) if body else None
        query_fields = {
            field.json_name: protojson_field_schema(field)
            for field in method.input_type.fields
            if field.name not in path_fields and field.name != body
        }
        operation: dict[str, Any] = {
            "auth": "bearer" if contract.bearer_auth else "none",
            "body": body or None,
            "bodyMessage": (
                body_field.message_type.full_name
                if body_field is not None and body_field.message_type is not None
                else None
            ),
            "method": verb.upper(),
            "operationId": method.name[0].lower() + method.name[1:],
            "operationKind": operation_kind,
            "pathFields": path_fields,
            "pathTemplate": path_template,
            "queryFields": query_fields,
            "requestHeaders": sorted(contract.request_headers),
            "requiredRequestHeaders": sorted(contract.required_request_headers),
            "requestBodyRequired": contract.request_body_required,
            "requestMessage": method.input_type.full_name,
            "responseHeaders": sorted(contract.response_headers),
            "responseMessage": method.output_type.full_name,
            "responseStatus": sorted([*contract.success_status, *contract.non_success_status]),
            "serverStreaming": method.server_streaming,
            "stream": stream_value.name,
            "successStatus": sorted(contract.success_status),
        }
        if sse is not None:
            operation["sse"] = sse
        operations.append(operation)
    return raw_openapi_document(
        sorted(operations, key=lambda item: cast(str, item["operationId"])),
        public_protojson_components(pool),
        sha256_bytes(descriptor_set),
    )


def project_descriptor_operation_extensions(
    raw: Mapping[str, Any],
    curated: dict[str, Any],
) -> None:
    """Project descriptor-owned operation metadata into the curated document."""
    contracts = {
        cast(str, contract["operationId"]): contract
        for contract in cast(list[dict[str, Any]], raw["x-mindclade-binding-contracts"])
    }
    for path_item in cast(dict[str, dict[str, Any]], curated["paths"]).values():
        for method, operation in path_item.items():
            if method not in OPENAPI_HTTP_METHODS:
                continue
            operation_id = operation.get("operationId")
            if not isinstance(operation_id, str) or operation_id not in contracts:
                continue
            contract = contracts[operation_id]
            operation_kind = contract["operationKind"]
            if (
                "x-mindclade-operation-kind" in operation
                and operation["x-mindclade-operation-kind"] != operation_kind
            ):
                raise ValueError(f"{operation_id}: descriptor operation-kind drift")
            operation["x-mindclade-operation-kind"] = operation_kind

            sse = contract.get("sse")
            if sse is None:
                if "x-mindclade-sse" in operation:
                    raise ValueError(f"{operation_id}: unexpected SSE policy")
                continue
            if "x-mindclade-sse" in operation and operation["x-mindclade-sse"] != sse:
                raise ValueError(f"{operation_id}: descriptor SSE-policy drift")
            operation["x-mindclade-sse"] = json.loads(json.dumps(sse))


def resolve_openapi_ref(document: Mapping[str, Any], value: Mapping[str, Any]) -> object:
    """Resolve one bundled OpenAPI reference without permitting external input."""
    ref = value.get("$ref")
    if not isinstance(ref, str):
        return value
    if not ref.startswith("#/"):
        raise ValueError(f"external OpenAPI reference is forbidden: {ref}")
    resolved: object = document
    for component in ref[2:].split("/"):
        key = component.replace("~1", "/").replace("~0", "~")
        if not isinstance(resolved, dict) or key not in resolved:
            raise ValueError(f"unresolved OpenAPI reference: {ref}")
        resolved = cast(dict[str, object], resolved)[key]
    return resolved


def schema_authority_names(value: object) -> set[str]:
    """Collect descriptor message identities declared inside one schema."""
    if isinstance(value, dict):
        mapping = cast(dict[str, object], value)
        result = {
            name
            for name in [mapping.get("x-mindclade-authoritative-message")]
            if isinstance(name, str)
        }
        for child in mapping.values():
            result.update(schema_authority_names(child))
        return result
    if isinstance(value, list):
        result: set[str] = set()
        for child in cast(list[object], value):
            result.update(schema_authority_names(child))
        return result
    return set()


def merged_openapi_object(
    document: Mapping[str, Any],
    schema: Mapping[str, Any],
) -> tuple[dict[str, Any], set[str]]:
    """Resolve object composition into its effective properties and required set."""
    resolved = resolve_openapi_ref(document, schema)
    if not isinstance(resolved, dict):
        raise ValueError("OpenAPI schema reference did not resolve to an object")
    resolved_mapping = cast(dict[str, object], resolved)
    properties = dict(cast(dict[str, Any], resolved_mapping.get("properties", {})))
    required = set(cast(list[str], resolved_mapping.get("required", [])))
    for part in cast(list[object], resolved_mapping.get("allOf", [])):
        if not isinstance(part, dict):
            raise ValueError("OpenAPI allOf member is not an object")
        child_properties, child_required = merged_openapi_object(
            document, cast(dict[str, Any], part)
        )
        overlap = set(properties).intersection(child_properties)
        if overlap:
            raise ValueError(f"OpenAPI allOf duplicates properties: {sorted(overlap)}")
        properties.update(child_properties)
        required.update(child_required)
    return properties, required


def validate_curated_protojson(
    raw: Mapping[str, Any],
    curated: Mapping[str, Any],
) -> None:
    """Reject curated component shapes that differ from descriptor ProtoJSON."""
    raw_components = cast(
        dict[str, dict[str, Any]], cast(dict[str, Any], raw["components"])["schemas"]
    )
    curated_components = cast(dict[str, dict[str, Any]], curated["components"]["schemas"])
    component_messages: dict[str, str] = {}
    for component_name, schema in curated_components.items():
        authorities = schema_authority_names(schema)
        if len(authorities) > 1:
            raise ValueError(
                f"OpenAPI component has multiple message authorities: {component_name}"
            )
        if authorities:
            component_messages[component_name] = next(iter(authorities))
            continue
        inferred = f"mindclade.api.v1.{component_name}"
        if inferred in raw_components:
            component_messages[component_name] = inferred

    validated_messages: set[str] = set()

    def validate_schema(
        curated_schema: Mapping[str, Any],
        raw_schema: Mapping[str, Any],
        context: str,
    ) -> None:
        expected_ref = raw_schema.get("$ref")
        if isinstance(expected_ref, str):
            expected_message = expected_ref.removeprefix("#/components/schemas/")
            curated_ref = curated_schema.get("$ref")
            if not isinstance(curated_ref, str) or not curated_ref.startswith(
                "#/components/schemas/"
            ):
                raise ValueError(f"{context}: expected a message schema reference")
            component_name = curated_ref.rsplit("/", 1)[1]
            actual_ref = component_messages.get(component_name)
            if actual_ref != expected_message:
                raise ValueError(
                    f"{context}: expected {expected_message}, got {actual_ref or component_name}"
                )
            validate_message(component_name, expected_message, context)
            return

        resolved = resolve_openapi_ref(curated, curated_schema)
        if not isinstance(resolved, dict):
            raise ValueError(f"{context}: schema did not resolve to an object")
        resolved_mapping = cast(dict[str, object], resolved)
        expected_type = raw_schema.get("type")
        actual_type = resolved_mapping.get("type")
        if expected_type != actual_type:
            raise ValueError(
                f"{context}: ProtoJSON type mismatch: expected {expected_type}, got {actual_type}"
            )
        if expected_type == "array":
            raw_items = raw_schema.get("items")
            actual_items = resolved_mapping.get("items")
            if not isinstance(raw_items, dict) or not isinstance(actual_items, dict):
                raise ValueError(f"{context}: array item schema is missing")
            validate_schema(
                cast(dict[str, Any], actual_items),
                cast(dict[str, Any], raw_items),
                f"{context}[]",
            )
        elif expected_type == "object" and "additionalProperties" in raw_schema:
            raw_values = raw_schema["additionalProperties"]
            actual_values = resolved_mapping.get("additionalProperties")
            if not isinstance(raw_values, dict) or not isinstance(actual_values, dict):
                raise ValueError(f"{context}: map value schema is missing")
            validate_schema(
                cast(dict[str, Any], actual_values),
                cast(dict[str, Any], raw_values),
                f"{context}{{}}",
            )
        expected_enum = raw_schema.get("enum")
        if expected_enum is not None and resolved_mapping.get("enum") != expected_enum:
            raise ValueError(f"{context}: ProtoJSON enum mismatch")
        expected_format = raw_schema.get("format")
        if expected_format is not None and resolved_mapping.get("format") != expected_format:
            actual_format = resolved_mapping.get("format")
            raise ValueError(f"{context}: expected format {expected_format}, got {actual_format}")

    def validate_message(component_name: str, message_name: str, context: str) -> None:
        if message_name in validated_messages:
            return
        validated_messages.add(message_name)
        raw_message = raw_components.get(message_name)
        if raw_message is None:
            raise ValueError(f"{context}: unknown descriptor message {message_name}")
        properties, required = merged_openapi_object(curated, curated_components[component_name])
        raw_properties = cast(dict[str, dict[str, Any]], raw_message["properties"])
        if set(properties) != set(raw_properties):
            raise ValueError(
                f"{context}: ProtoJSON property drift for {message_name}: "
                f"curated-only={sorted(set(properties) - set(raw_properties))}, "
                f"descriptor-only={sorted(set(raw_properties) - set(properties))}"
            )
        expected_required = set(cast(list[str], raw_message["required"]))
        if required != expected_required:
            raise ValueError(
                f"{context}: requiredness drift for {message_name}: "
                f"curated={sorted(required)}, descriptor={sorted(expected_required)}"
            )
        for field_name, raw_field in raw_properties.items():
            validate_schema(
                cast(dict[str, Any], properties[field_name]),
                raw_field,
                f"{context}.{field_name}",
            )

    def operation_schema(operation: Mapping[str, Any], success_status: int) -> dict[str, Any]:
        response = cast(dict[str, Any], operation["responses"][str(success_status)])
        response = cast(dict[str, Any], resolve_openapi_ref(curated, response))
        content = cast(dict[str, dict[str, Any]], response.get("content", {}))
        for media_type in ("application/json", "text/event-stream"):
            if media_type in content:
                return cast(dict[str, Any], content[media_type]["schema"])
        raise ValueError(f"operation response has no ProtoJSON schema: {operation['operationId']}")

    operation_by_id = {
        operation["operationId"]: operation
        for path_item in cast(dict[str, dict[str, Any]], curated["paths"]).values()
        for method, operation in path_item.items()
        if method in {"delete", "get", "patch", "post", "put"}
    }
    for raw_operation in cast(list[dict[str, Any]], raw["x-mindclade-binding-contracts"]):
        operation_id = cast(str, raw_operation["operationId"])
        operation = operation_by_id[operation_id]
        body_message = raw_operation.get("bodyMessage")
        if isinstance(body_message, str):
            body = cast(dict[str, Any], operation["requestBody"])
            content = cast(dict[str, dict[str, Any]], body["content"])
            validate_schema(
                cast(dict[str, Any], content["application/json"]["schema"]),
                {"$ref": "#/components/schemas/" + body_message},
                f"{operation_id}.request",
            )
        validate_schema(
            operation_schema(operation, cast(list[int], raw_operation["successStatus"])[0]),
            {"$ref": "#/components/schemas/" + raw_operation["responseMessage"]},
            f"{operation_id}.response",
        )
        for status_code in cast(list[int], raw_operation["responseStatus"]):
            if status_code in raw_operation["successStatus"] or status_code == 304:
                continue
            error_response = cast(
                dict[str, Any],
                resolve_openapi_ref(
                    curated,
                    cast(dict[str, Any], operation["responses"][str(status_code)]),
                ),
            )
            error_content = cast(dict[str, dict[str, Any]], error_response["content"])
            validate_schema(
                cast(dict[str, Any], error_content["application/problem+json"]["schema"]),
                {"$ref": "#/components/schemas/mindclade.api.v1.PublicError"},
                f"{operation_id}.error.{status_code}",
            )
    for component_name, message_name in sorted(component_messages.items()):
        validate_message(component_name, message_name, f"component.{component_name}")


def validate_curated_bindings(
    raw: Mapping[str, Any],
    curated: Mapping[str, Any],
) -> None:
    """Prove method, path, query, body, auth, status, header, and stream parity."""
    methods = {"delete", "get", "patch", "post", "put"}
    operations: dict[str, tuple[str, str, dict[str, Any]]] = {}
    for path, path_item in cast(dict[str, dict[str, Any]], curated["paths"]).items():
        for method, operation in path_item.items():
            if method in methods:
                operations[operation["operationId"]] = (method.upper(), path, operation)
    raw_operations = {
        cast(str, operation["operationId"]): operation
        for operation in cast(list[dict[str, Any]], raw["x-mindclade-binding-contracts"])
    }
    if set(operations) != set(raw_operations):
        raise ValueError(
            "raw/curated public operation mismatch: "
            f"raw-only={sorted(set(raw_operations) - set(operations))}, "
            f"curated-only={sorted(set(operations) - set(raw_operations))}"
        )

    def parameters(operation: Mapping[str, Any]) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = []
        for raw_parameter in cast(list[object], operation.get("parameters", [])):
            if not isinstance(raw_parameter, dict):
                raise ValueError("OpenAPI operation parameter is not an object")
            parameter = resolve_openapi_ref(curated, cast(dict[str, Any], raw_parameter))
            if not isinstance(parameter, dict):
                raise ValueError("OpenAPI parameter did not resolve to an object")
            result.append(cast(dict[str, Any], parameter))
        return result

    global_security = curated.get("security")
    for operation_id, raw_operation in raw_operations.items():
        method, path, operation = operations[operation_id]
        if method != raw_operation["method"]:
            raise ValueError(f"{operation_id}: HTTP method drift")
        if operation.get("x-mindclade-operation-kind") != raw_operation["operationKind"]:
            raise ValueError(f"{operation_id}: descriptor operation-kind drift")
        expected_sse = raw_operation.get("sse")
        if expected_sse is None:
            if "x-mindclade-sse" in operation:
                raise ValueError(f"{operation_id}: unexpected SSE policy")
        elif operation.get("x-mindclade-sse") != expected_sse:
            raise ValueError(f"{operation_id}: descriptor SSE-policy drift")
        expected_path, expected_path_parameters = expand_google_http_path(
            cast(str, raw_operation["pathTemplate"])
        )
        if path != expected_path:
            raise ValueError(f"{operation_id}: HTTP path binding drift")
        effective_security = operation.get("security", global_security)
        if raw_operation["auth"] == "bearer" and effective_security != [{"bearerAuth": []}]:
            raise ValueError(f"{operation_id}: bearer authentication drift")
        operation_parameters = parameters(operation)
        request_headers = sorted(
            parameter["name"] for parameter in operation_parameters if parameter["in"] == "header"
        )
        if request_headers != raw_operation["requestHeaders"]:
            raise ValueError(f"{operation_id}: request-header binding drift")
        required_request_headers = sorted(
            parameter["name"]
            for parameter in operation_parameters
            if parameter["in"] == "header" and parameter.get("required") is True
        )
        if required_request_headers != raw_operation["requiredRequestHeaders"]:
            raise ValueError(f"{operation_id}: request-header requiredness drift")
        query = {
            parameter["name"]: parameter
            for parameter in operation_parameters
            if parameter["in"] == "query"
        }
        raw_query = cast(dict[str, dict[str, Any]], raw_operation["queryFields"])
        if set(query) != set(raw_query):
            raise ValueError(f"{operation_id}: query binding drift")
        for name, raw_schema in raw_query.items():
            parameter_schema = query[name].get("schema")
            if not isinstance(parameter_schema, dict):
                raise ValueError(f"{operation_id}.{name}: query schema is missing")
            resolved = resolve_openapi_ref(curated, cast(dict[str, object], parameter_schema))
            if not isinstance(resolved, dict):
                raise ValueError(f"{operation_id}.{name}: query schema is not an object")
            resolved_mapping = cast(dict[str, object], resolved)
            if resolved_mapping.get("type") != raw_schema.get("type"):
                raise ValueError(f"{operation_id}.{name}: query ProtoJSON type drift")
            if raw_schema.get("format") is not None and resolved_mapping.get(
                "format"
            ) != raw_schema.get("format"):
                raise ValueError(f"{operation_id}.{name}: query ProtoJSON format drift")
        has_body = "requestBody" in operation
        if has_body != bool(raw_operation["body"]):
            raise ValueError(f"{operation_id}: request-body binding drift")
        if has_body and bool(operation["requestBody"].get("required")) != bool(
            raw_operation["requestBodyRequired"]
        ):
            raise ValueError(f"{operation_id}: request-body requiredness drift")
        path_parameters = [
            parameter for parameter in operation_parameters if parameter["in"] == "path"
        ]
        if any(parameter.get("required") is not True for parameter in path_parameters):
            raise ValueError(f"{operation_id}: path parameters must be required")
        path_parameter_names = [parameter.get("name") for parameter in path_parameters]
        if any(not isinstance(name, str) for name in path_parameter_names) or sorted(
            cast(list[str], path_parameter_names)
        ) != sorted(expected_path_parameters):
            raise ValueError(f"{operation_id}: path-parameter binding drift")
        if any(parameter.get("required") is True for parameter in query.values()):
            raise ValueError(f"{operation_id}: optional query-field requiredness drift")
        response_status = sorted(int(code) for code in operation["responses"])
        if response_status != raw_operation["responseStatus"]:
            raise ValueError(f"{operation_id}: documented response-status drift")
        success_status = sorted(
            int(code) for code in operation["responses"] if str(code).startswith("2")
        )
        if success_status != raw_operation["successStatus"]:
            raise ValueError(f"{operation_id}: success-status drift")
        response = cast(
            dict[str, Any],
            resolve_openapi_ref(
                curated, cast(dict[str, Any], operation["responses"][str(success_status[0])])
            ),
        )
        response_headers = sorted(cast(dict[str, Any], response.get("headers", {})))
        if response_headers != raw_operation["responseHeaders"]:
            raise ValueError(f"{operation_id}: response-header binding drift")
        content_types = set(cast(dict[str, Any], response.get("content", {})))
        expected_content = (
            {"text/event-stream"}
            if raw_operation["stream"] == "STREAM_PROJECTION_SSE"
            else {"application/octet-stream"}
            if raw_operation["stream"] == "STREAM_PROJECTION_BINARY"
            else {"application/json"}
        )
        if content_types != expected_content:
            raise ValueError(f"{operation_id}: response media-type/stream drift")
        for status_code in raw_operation["responseStatus"]:
            if status_code in raw_operation["successStatus"]:
                continue
            error_response = cast(
                dict[str, Any],
                resolve_openapi_ref(
                    curated,
                    cast(dict[str, Any], operation["responses"][str(status_code)]),
                ),
            )
            if error_response.get("headers"):
                raise ValueError(f"{operation_id}.{status_code}: response-header drift")
            error_content = set(cast(dict[str, Any], error_response.get("content", {})))
            expected_error_content: set[str] = (
                set() if status_code == 304 else {"application/problem+json"}
            )
            if error_content != expected_error_content:
                raise ValueError(f"{operation_id}.{status_code}: error media-type/body drift")


def curate_openapi_overlay(overlay: Mapping[str, Any]) -> dict[str, Any]:
    """Apply deterministic, semantics-preserving curation to the public overlay."""
    curated = cast(dict[str, Any], json.loads(json.dumps(overlay)))
    components = cast(dict[str, dict[str, Any]], curated.get("components", {}))
    reachable: dict[str, set[str]] = defaultdict(set)
    pending: list[str] = []

    def collect_references(value: object) -> None:
        if isinstance(value, dict):
            for key, child in cast(dict[str, object], value).items():
                if key == "$ref" and isinstance(child, str):
                    pending.append(child)
                else:
                    collect_references(child)
        elif isinstance(value, list):
            for child in cast(list[object], value):
                collect_references(child)

    collect_references(curated.get("paths", {}))
    while pending:
        reference = pending.pop()
        match = re.fullmatch(r"#/components/([^/]+)/([^/]+)", reference)
        if match is None:
            raise ValueError(f"curation encountered an unsupported reference: {reference}")
        section, name = match.groups()
        if name in reachable[section]:
            continue
        values = components.get(section)
        if values is None or name not in values:
            raise ValueError(f"curation encountered an unresolved reference: {reference}")
        reachable[section].add(name)
        collect_references(values[name])

    security_names: set[str] = set()
    for security in cast(list[object], curated.get("security", [])):
        if isinstance(security, dict):
            security_names.update(cast(dict[str, Any], security))
    for path_item in cast(dict[str, dict[str, Any]], curated.get("paths", {})).values():
        for operation in path_item.values():
            if not isinstance(operation, dict):
                continue
            operation_mapping = cast(dict[str, object], operation)
            for security in cast(list[object], operation_mapping.get("security", [])):
                if isinstance(security, dict):
                    security_names.update(cast(dict[str, Any], security))
    reachable["securitySchemes"].update(security_names)

    curated_components: dict[str, Any] = {}
    for section, values in components.items():
        selected = reachable.get(section, set())
        if selected:
            curated_components[section] = {
                name: values[name] for name in values if name in selected
            }
    curated["components"] = curated_components
    return curated


def openapi_pipeline_outputs(root: Path, descriptor_set: bytes) -> dict[Path, bytes]:
    """Return checked raw, curated, and published OpenAPI candidate stages."""
    raw = public_openapi_projection(descriptor_set)
    curated_source = root / "protocols/openapi/external-api.yaml"
    raw_overlay: object = yaml.safe_load(curated_source.read_text(encoding="utf-8"))
    if not isinstance(raw_overlay, dict):
        raise ValueError("curated OpenAPI document is not an object")
    overlay = cast(dict[str, object], raw_overlay)
    if not isinstance(overlay.get("paths"), dict):
        raise ValueError("curated OpenAPI document has no paths object")
    curated = curate_openapi_overlay(overlay)
    project_descriptor_operation_extensions(raw, curated)
    descriptor_digest = raw.get("x-mindclade-descriptor-digest")
    if not isinstance(descriptor_digest, str):
        raise ValueError("raw OpenAPI projection has no descriptor digest")
    curated["x-mindclade-descriptor-digest"] = descriptor_digest
    validate_curated_bindings(raw, curated)
    validate_curated_protojson(raw, curated)
    curated_bytes = (
        "# Code generated by mindclade-contract-codegen. DO NOT EDIT.\n" + dump_yaml(curated)
    ).encode()
    raw_bytes = (
        "# Code generated by mindclade-contract-codegen. DO NOT EDIT.\n" + dump_yaml(raw)
    ).encode()
    return {
        root / "protocols/openapi/raw/mindclade.openapi.yaml": raw_bytes,
        root / "protocols/openapi/curated/mindclade.openapi.yaml": curated_bytes,
        root / "protocols/openapi/published/mindclade.openapi.yaml": curated_bytes,
    }


def openapi_candidate_lock(root: Path, generated: Mapping[Path, bytes]) -> bytes:
    """Bind every editable and generated OpenAPI candidate source by digest."""
    openapi_root = root / "protocols/openapi"
    sources = {
        path
        for path in openapi_root.rglob("*")
        if path.is_file() and path.suffix in {".json", ".yaml"}
    }
    sources.update(generated)
    digests: dict[str, str] = {}
    for path in sorted(sources):
        content = generated[path] if path in generated else path.read_bytes()
        digests[path.relative_to(root).as_posix()] = sha256_bytes(content)
    return (
        json.dumps(
            {
                "schema_version": "mindclade.openapi-candidate/v1",
                "sources": digests,
            },
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode()


def _openapi_mapping(value: object) -> Mapping[str, object] | None:
    """Narrow a decoded OpenAPI object without leaking an unknown value type."""

    if not isinstance(value, Mapping):
        return None
    return cast(Mapping[str, object], value)


def _openapi_list(value: object) -> list[object] | None:
    """Narrow a decoded OpenAPI array without leaking an unknown item type."""

    if not isinstance(value, list):
        return None
    return cast(list[object], value)


def _openapi_local_ref(document: Mapping[str, object], value: object) -> object:
    if not isinstance(value, str) or not value.startswith("#/"):
        raise ValueError(f"ratified OpenAPI contains an unsupported reference: {value!r}")
    current: object = document
    for raw_part in value[2:].split("/"):
        part = raw_part.replace("~1", "/").replace("~0", "~")
        current_mapping = _openapi_mapping(current)
        if current_mapping is None or part not in current_mapping:
            raise ValueError(f"ratified OpenAPI contains an unresolved reference: {value}")
        current = current_mapping[part]
    return current


def _openapi_resolved_mapping(
    document: Mapping[str, object], value: object
) -> Mapping[str, object] | None:
    """Return an inline or locally referenced OpenAPI object."""

    mapping = _openapi_mapping(value)
    if mapping is not None and "$ref" in mapping:
        return _openapi_mapping(_openapi_local_ref(document, mapping["$ref"]))
    return mapping


def _openapi_schema_compatible(
    baseline_document: Mapping[str, object],
    current_document: Mapping[str, object],
    baseline: object,
    current: object,
    *,
    request: bool,
    location: str,
    visited: set[tuple[str, str, bool]],
) -> None:
    """Reject schema changes forbidden by the governed additive-v1 policy."""

    baseline_schema = _openapi_mapping(baseline)
    current_schema = _openapi_mapping(current)
    if baseline_schema is None or current_schema is None:
        if baseline != current:
            raise ValueError(f"OpenAPI compatibility break at {location}: schema shape changed")
        return
    baseline_ref = baseline_schema.get("$ref")
    current_ref = current_schema.get("$ref")
    if baseline_ref is not None or current_ref is not None:
        if not isinstance(baseline_ref, str) or not isinstance(current_ref, str):
            raise ValueError(f"OpenAPI compatibility break at {location}: reference changed")
        key = (baseline_ref, current_ref, request)
        if key in visited:
            return
        visited.add(key)
        _openapi_schema_compatible(
            baseline_document,
            current_document,
            _openapi_local_ref(baseline_document, baseline_ref),
            _openapi_local_ref(current_document, current_ref),
            request=request,
            location=f"{location} ({baseline_ref})",
            visited=visited,
        )
        return

    for field in (
        "type",
        "format",
        "const",
        "pattern",
        "contentEncoding",
        "contentMediaType",
        "x-mindclade-authoritative-message",
    ):
        if baseline_schema.get(field) != current_schema.get(field):
            raise ValueError(f"OpenAPI compatibility break at {location}: {field} changed")
    baseline_enum = baseline_schema.get("enum")
    current_enum = current_schema.get("enum")
    if baseline_enum is not None:
        baseline_enum_values = _openapi_list(baseline_enum)
        current_enum_values = _openapi_list(current_enum)
        if baseline_enum_values is None or current_enum_values is None:
            raise ValueError(f"OpenAPI compatibility break at {location}: enum changed")
        incompatible_values = (
            set(baseline_enum_values) - set(current_enum_values)
            if request
            else set(current_enum_values) - set(baseline_enum_values)
        )
        if incompatible_values:
            direction = "removed from request" if request else "added to response"
            raise ValueError(
                f"OpenAPI compatibility break at {location}: enum values {direction} "
                f"{sorted(incompatible_values, key=repr)}"
            )

    lower_bounds = ("minimum", "exclusiveMinimum", "minLength", "minItems", "minProperties")
    upper_bounds = ("maximum", "exclusiveMaximum", "maxLength", "maxItems", "maxProperties")
    for field in lower_bounds:
        old = baseline_schema.get(field)
        new = current_schema.get(field)
        if request:
            incompatible = (old is None and new is not None) or (
                old is not None and new is not None and cast(float, new) > cast(float, old)
            )
        else:
            incompatible = (old is not None and new is None) or (
                old is not None and new is not None and cast(float, new) < cast(float, old)
            )
        if incompatible:
            direction = "tightened for requests" if request else "loosened for responses"
            raise ValueError(f"OpenAPI compatibility break at {location}: {field} was {direction}")
    for field in upper_bounds:
        old = baseline_schema.get(field)
        new = current_schema.get(field)
        if request:
            incompatible = (old is None and new is not None) or (
                old is not None and new is not None and cast(float, new) < cast(float, old)
            )
        else:
            incompatible = (old is not None and new is None) or (
                old is not None and new is not None and cast(float, new) > cast(float, old)
            )
        if incompatible:
            direction = "tightened for requests" if request else "loosened for responses"
            raise ValueError(f"OpenAPI compatibility break at {location}: {field} was {direction}")
    old_additional = baseline_schema.get("additionalProperties", True)
    new_additional = current_schema.get("additionalProperties", True)
    if (request and old_additional is not False and new_additional is False) or (
        not request and old_additional is False and new_additional is not False
    ):
        raise ValueError(
            f"OpenAPI compatibility break at {location}: additional-properties variance changed"
        )

    baseline_properties = _openapi_mapping(baseline_schema.get("properties", {}))
    current_properties = _openapi_mapping(current_schema.get("properties", {}))
    if baseline_properties is None or current_properties is None:
        raise ValueError(f"OpenAPI compatibility break at {location}: properties changed")
    removed = set(baseline_properties) - set(current_properties)
    if removed:
        raise ValueError(
            f"OpenAPI compatibility break at {location}: properties removed {sorted(removed)}"
        )
    baseline_required = _openapi_list(baseline_schema.get("required", []))
    current_required = _openapi_list(current_schema.get("required", []))
    if baseline_required is None or current_required is None:
        raise ValueError(f"OpenAPI compatibility break at {location}: required fields changed")
    if request:
        newly_required = set(current_required) - set(baseline_required)
        if newly_required:
            raise ValueError(
                f"OpenAPI compatibility break at {location}: request fields became required "
                f"{sorted(newly_required, key=repr)}"
            )
    else:
        no_longer_required = set(baseline_required) - set(current_required)
        if no_longer_required:
            raise ValueError(
                f"OpenAPI compatibility break at {location}: response fields became optional "
                f"{sorted(no_longer_required, key=repr)}"
            )
    for name, old_property in baseline_properties.items():
        _openapi_schema_compatible(
            baseline_document,
            current_document,
            old_property,
            current_properties[name],
            request=request,
            location=f"{location}.properties.{name}",
            visited=visited,
        )

    if "items" in baseline_schema or "items" in current_schema:
        if "items" not in baseline_schema or "items" not in current_schema:
            raise ValueError(f"OpenAPI compatibility break at {location}: array items changed")
        _openapi_schema_compatible(
            baseline_document,
            current_document,
            baseline_schema["items"],
            current_schema["items"],
            request=request,
            location=f"{location}.items",
            visited=visited,
        )
    for composition in ("allOf", "anyOf", "oneOf"):
        raw_old_shapes = baseline_schema.get(composition)
        raw_new_shapes = current_schema.get(composition)
        if raw_old_shapes is None and raw_new_shapes is None:
            continue
        old_shapes = _openapi_list(raw_old_shapes)
        new_shapes = _openapi_list(raw_new_shapes)
        if old_shapes is None or new_shapes is None or len(old_shapes) != len(new_shapes):
            raise ValueError(f"OpenAPI compatibility break at {location}: {composition} changed")
        for index, old_shape in enumerate(old_shapes):
            _openapi_schema_compatible(
                baseline_document,
                current_document,
                old_shape,
                new_shapes[index],
                request=request,
                location=f"{location}.{composition}[{index}]",
                visited=visited,
            )


def validate_openapi_compatibility(
    baseline_bytes: bytes,
    current_bytes: bytes,
) -> None:
    """Enforce the post-Stage-5 additive compatibility policy."""

    baseline_value: object = yaml.safe_load(baseline_bytes)
    current_value: object = yaml.safe_load(current_bytes)
    if not isinstance(baseline_value, dict) or not isinstance(current_value, dict):
        raise ValueError("ratified and candidate OpenAPI documents must be objects")
    baseline = cast(dict[str, object], baseline_value)
    current = cast(dict[str, object], current_value)
    for field in ("openapi", "jsonSchemaDialect", "security"):
        if baseline.get(field) != current.get(field):
            raise ValueError(f"OpenAPI compatibility break: top-level {field} changed")
    baseline_paths = _openapi_mapping(baseline.get("paths"))
    current_paths = _openapi_mapping(current.get("paths"))
    if baseline_paths is None or current_paths is None:
        raise ValueError("ratified and candidate OpenAPI paths must be objects")
    http_methods = {"delete", "get", "head", "options", "patch", "post", "put", "trace"}
    for path, raw_baseline_path in baseline_paths.items():
        raw_current_path = current_paths.get(path)
        baseline_path = _openapi_mapping(raw_baseline_path)
        current_path = _openapi_mapping(raw_current_path)
        if baseline_path is None or current_path is None:
            raise ValueError(f"OpenAPI compatibility break: path removed {path}")
        for method, raw_baseline_operation in baseline_path.items():
            if method not in http_methods:
                continue
            raw_current_operation = current_path.get(method)
            old_operation = _openapi_mapping(raw_baseline_operation)
            new_operation = _openapi_mapping(raw_current_operation)
            if old_operation is None or new_operation is None:
                raise ValueError(f"OpenAPI compatibility break: operation removed {method} {path}")
            location = f"{method.upper()} {path}"
            for field in (
                "operationId",
                "security",
                "x-mindclade-operation-kind",
                "x-mindclade-sse",
            ):
                if old_operation.get(field) != new_operation.get(field):
                    raise ValueError(f"OpenAPI compatibility break at {location}: {field} changed")

            def resolved_parameters(
                document: Mapping[str, object],
                operation: Mapping[str, object],
                operation_location: str,
            ) -> dict[tuple[str, str], Mapping[str, object]]:
                result: dict[tuple[str, str], Mapping[str, object]] = {}
                raw_parameters = _openapi_list(operation.get("parameters", []))
                if raw_parameters is None:
                    raise ValueError(
                        f"OpenAPI compatibility break at {operation_location}: parameters changed"
                    )
                for raw_parameter in raw_parameters:
                    parameter = raw_parameter
                    parameter_mapping = _openapi_mapping(parameter)
                    if parameter_mapping is not None and "$ref" in parameter_mapping:
                        parameter = _openapi_local_ref(document, parameter_mapping["$ref"])
                        parameter_mapping = _openapi_mapping(parameter)
                    if parameter_mapping is None:
                        raise ValueError(
                            "OpenAPI compatibility break at "
                            f"{operation_location}: parameter changed"
                        )
                    key = (
                        str(parameter_mapping.get("in")),
                        str(parameter_mapping.get("name")),
                    )
                    if key in result:
                        raise ValueError(
                            "OpenAPI compatibility break at "
                            f"{operation_location}: duplicate parameter {key}"
                        )
                    result[key] = parameter_mapping
                return result

            old_parameters = resolved_parameters(baseline, old_operation, location)
            new_parameters = resolved_parameters(current, new_operation, location)
            for key, old_parameter in old_parameters.items():
                new_parameter = new_parameters.get(key)
                if new_parameter is None:
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: parameter removed {key}"
                    )
                if not old_parameter.get("required", False) and new_parameter.get(
                    "required", False
                ):
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: "
                        f"parameter became required {key}"
                    )
                for field in ("style", "explode", "allowReserved"):
                    if old_parameter.get(field) != new_parameter.get(field):
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: "
                            f"parameter {key} {field} changed"
                        )
                _openapi_schema_compatible(
                    baseline,
                    current,
                    old_parameter.get("schema", {}),
                    new_parameter.get("schema", {}),
                    request=True,
                    location=f"{location} parameter {key}",
                    visited=set(),
                )
            for key, parameter in new_parameters.items():
                if key not in old_parameters and parameter.get("required", False):
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: new required parameter {key}"
                    )

            raw_old_body = old_operation.get("requestBody")
            raw_new_body = new_operation.get("requestBody")
            if raw_old_body is not None or raw_new_body is not None:
                old_body = _openapi_resolved_mapping(baseline, raw_old_body)
                new_body = _openapi_resolved_mapping(current, raw_new_body)
                if raw_old_body is None:
                    if new_body is None or new_body.get("required", False):
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: required body added"
                        )
                elif old_body is None or new_body is None:
                    raise ValueError(f"OpenAPI compatibility break at {location}: body removed")
                else:
                    if not old_body.get("required", False) and new_body.get("required", False):
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: body became required"
                        )
                    old_content = _openapi_mapping(old_body.get("content", {}))
                    new_content = _openapi_mapping(new_body.get("content", {}))
                    if old_content is None or new_content is None:
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: body content changed"
                        )
                    for media_type, old_media in old_content.items():
                        new_media = new_content.get(media_type)
                        old_media_mapping = _openapi_mapping(old_media)
                        new_media_mapping = _openapi_mapping(new_media)
                        if old_media_mapping is None or new_media_mapping is None:
                            raise ValueError(
                                f"OpenAPI compatibility break at {location}: "
                                "request media type removed"
                            )
                        _openapi_schema_compatible(
                            baseline,
                            current,
                            old_media_mapping.get("schema", {}),
                            new_media_mapping.get("schema", {}),
                            request=True,
                            location=f"{location} request {media_type}",
                            visited=set(),
                        )

            old_responses = _openapi_mapping(old_operation.get("responses"))
            new_responses = _openapi_mapping(new_operation.get("responses"))
            if old_responses is None or new_responses is None:
                raise ValueError(f"OpenAPI compatibility break at {location}: responses changed")
            for status, old_response_value in old_responses.items():
                new_response_value = new_responses.get(status)
                old_response = _openapi_resolved_mapping(baseline, old_response_value)
                new_response = _openapi_resolved_mapping(current, new_response_value)
                if old_response is None or new_response is None:
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: response removed {status}"
                    )
                old_headers = _openapi_mapping(old_response.get("headers", {}))
                new_headers = _openapi_mapping(new_response.get("headers", {}))
                if old_headers is None or new_headers is None:
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: response headers changed"
                    )
                for header_name, old_header_value in old_headers.items():
                    new_header_value = new_headers.get(header_name)
                    old_header = _openapi_resolved_mapping(baseline, old_header_value)
                    new_header = _openapi_resolved_mapping(current, new_header_value)
                    if old_header is None or new_header is None:
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: "
                            f"response header removed {status} {header_name}"
                        )
                    _openapi_schema_compatible(
                        baseline,
                        current,
                        old_header.get("schema", {}),
                        new_header.get("schema", {}),
                        request=False,
                        location=f"{location} response {status} header {header_name}",
                        visited=set(),
                    )
                old_content = _openapi_mapping(old_response.get("content", {}))
                new_content = _openapi_mapping(new_response.get("content", {}))
                if old_content is None or new_content is None:
                    raise ValueError(
                        f"OpenAPI compatibility break at {location}: response content changed"
                    )
                for media_type, old_media in old_content.items():
                    new_media = new_content.get(media_type)
                    old_media_mapping = _openapi_mapping(old_media)
                    new_media_mapping = _openapi_mapping(new_media)
                    if old_media_mapping is None or new_media_mapping is None:
                        raise ValueError(
                            f"OpenAPI compatibility break at {location}: "
                            "response media type removed"
                        )
                    _openapi_schema_compatible(
                        baseline,
                        current,
                        old_media_mapping.get("schema", {}),
                        new_media_mapping.get("schema", {}),
                        request=False,
                        location=f"{location} response {status} {media_type}",
                        visited=set(),
                    )

    baseline_components = _openapi_mapping(baseline.get("components", {}))
    current_components = _openapi_mapping(current.get("components", {}))
    baseline_schemas = _openapi_mapping(
        baseline_components.get("schemas", {}) if baseline_components is not None else None
    )
    current_schemas = _openapi_mapping(
        current_components.get("schemas", {}) if current_components is not None else None
    )
    if baseline_schemas is None or current_schemas is None:
        raise ValueError("OpenAPI compatibility break: component schemas changed")
    for name, baseline_schema in baseline_schemas.items():
        if name not in current_schemas:
            raise ValueError(f"OpenAPI compatibility break: schema removed {name}")
        _openapi_schema_compatible(
            baseline,
            current,
            baseline_schema,
            current_schemas[name],
            request=False,
            location=f"components.schemas.{name}",
            visited=set(),
        )


def ratified_openapi_baseline(
    published_openapi: bytes,
    *,
    descriptor_digest: str,
    bindings: Mapping[str, Any],
    evidence: Mapping[str, Any],
    evidence_digest: str,
    authorization: Mapping[str, str],
) -> bytes:
    """Construct the immutable public v1 baseline in the protected transaction."""

    value = {
        "document": {
            "base64": base64.b64encode(published_openapi).decode("ascii"),
            "digest": sha256_bytes(published_openapi),
        },
        "descriptor_digest": descriptor_digest,
        "ratification": {
            "authority": "docs/adr/0015-all-contracts-clean-v1-baseline.md",
            "bindings": dict(bindings),
            "evidence_digest": evidence_digest,
            "evidence_schema_version": evidence["schema_version"],
            "protected_authorization": dict(sorted(authorization.items())),
            "source_revision": bindings["source_revision"],
        },
        "schema_version": "mindclade.openapi-baseline/v1",
    }
    return (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()


def ratified_openapi_document(content: bytes) -> bytes | None:
    """Return a validated baseline document, or None for the unratified candidate lock."""

    try:
        value: object = json.loads(content)
    except json.JSONDecodeError as error:
        raise ValueError("OpenAPI compatibility artifact is not valid JSON") from error
    if not isinstance(value, dict):
        raise ValueError("OpenAPI compatibility artifact must be an object")
    artifact = cast(dict[str, object], value)
    if artifact.get("schema_version") == "mindclade.openapi-candidate/v1":
        return None
    if artifact.get("schema_version") != "mindclade.openapi-baseline/v1" or set(artifact) != {
        "descriptor_digest",
        "document",
        "ratification",
        "schema_version",
    }:
        raise ValueError("OpenAPI compatibility artifact has an unsupported baseline format")
    document = _openapi_mapping(artifact.get("document"))
    if document is None or set(document) != {"base64", "digest"}:
        raise ValueError("OpenAPI baseline document binding is malformed")
    encoded = document.get("base64")
    if not isinstance(encoded, str):
        raise ValueError("OpenAPI baseline document has no canonical bytes")
    try:
        decoded = base64.b64decode(encoded, validate=True)
    except ValueError as error:
        raise ValueError("OpenAPI baseline document is not canonical base64") from error
    if base64.b64encode(decoded).decode("ascii") != encoded:
        raise ValueError("OpenAPI baseline document is not canonical base64")
    if document.get("digest") != sha256_bytes(decoded):
        raise ValueError("OpenAPI baseline document digest does not match")
    return decoded


def validate_staged_descriptor_joins(
    root: Path,
    outputs: Mapping[Path, bytes],
    descriptor_digest: str,
) -> None:
    """Prove every staged projection is joined to the same descriptor image."""

    json_fields = {
        PROTOBUF_CANDIDATE: ("descriptor_set", "digest"),
        SDK_RPC_COVERAGE: ("descriptor_digest",),
        GRPC_IMPLEMENTATION_COVERAGE: ("descriptor_digest",),
        GENERATED_MANIFEST: ("descriptor_digest",),
    }
    for relative, field_path in json_fields.items():
        content = outputs.get(root / relative)
        if content is None:
            if relative == GENERATED_MANIFEST:
                continue
            raise ValueError(f"staged descriptor projection is absent: {relative}")
        value: object = json.loads(content)
        for field in field_path:
            if not isinstance(value, dict):
                raise ValueError(f"staged descriptor projection is malformed: {relative}")
            value = cast(dict[str, object], value).get(field)
        if value != descriptor_digest:
            raise ValueError(
                f"staged descriptor digest mismatch in {relative}: "
                f"expected {descriptor_digest}, got {value!r}"
            )

    for relative in (
        Path("protocols/openapi/raw/mindclade.openapi.yaml"),
        Path("protocols/openapi/curated/mindclade.openapi.yaml"),
        Path("protocols/openapi/published/mindclade.openapi.yaml"),
    ):
        content = outputs.get(root / relative)
        if content is None:
            raise ValueError(f"staged OpenAPI projection is absent: {relative}")
        value: object = yaml.safe_load(content)
        if (
            not isinstance(value, dict)
            or cast(dict[str, object], value).get("x-mindclade-descriptor-digest")
            != descriptor_digest
        ):
            raise ValueError(f"staged OpenAPI descriptor digest mismatch: {relative}")

    # Formatters may adjust type spelling or whitespace around these declarations.
    # Require both the language-specific authority symbol and the exact shared
    # descriptor digest instead of coupling the join check to formatter output.
    registry_markers = {
        Path("protocols/generated/python/mindclade/events/registry.py"): b"EVENT_DESCRIPTOR_DIGEST",
        Path("protocols/generated/rust/lib.rs"): b"EVENT_DESCRIPTOR_DIGEST",
        Path("protocols/generated/typescript/common/v1/index.ts"): b"EVENT_DESCRIPTOR_DIGEST",
        Path("services/control_plane/internal/platform/queue/event_registry_generated.go"): (
            b"authoritativeEventDescriptorDigest"
        ),
    }
    descriptor_marker = descriptor_digest.encode()
    for relative, symbol in registry_markers.items():
        content = outputs.get(root / relative)
        if content is None or symbol not in content or descriptor_marker not in content:
            raise ValueError(f"staged event registry descriptor digest mismatch: {relative}")


