def generation_authority_digest(root: Path) -> str:
    """Snapshot every tracked or review-visible source before a staged build."""

    raw_paths = run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=root,
    ).stdout
    material = bytearray()
    for raw_relative in sorted(value for value in raw_paths.split(b"\x00") if value):
        relative = Path(os.fsdecode(raw_relative))
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError(f"unsafe repository source path: {relative}")
        path = root / relative
        material.extend(raw_relative)
        material.extend(b"\x00")
        if path.is_symlink():
            material.extend(b"symlink:\x00")
            material.extend(os.fsencode(path.readlink()))
        elif path.is_file():
            material.extend(b"file:\x00")
            material.extend(hashlib.sha256(path.read_bytes()).digest())
        else:
            material.extend(b"missing:\x00")
        material.extend(b"\x00")
    return sha256_bytes(bytes(material))


@contextmanager
def exclusive_generation_lock(root: Path) -> Generator[None, None, None]:
    """Serialize complete contract transactions without mutating authority files."""

    lock_root = root / "build/codegen"
    lock_root.mkdir(parents=True, exist_ok=True)
    lock_path = lock_root / "generation.lock"
    with lock_path.open("a+b") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def atomic_replace_generated_file(path: Path, content: bytes, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        prefix=f".{path.name}.",
        dir=path.parent,
        delete=False,
    ) as handle:
        temporary = Path(handle.name)
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        temporary.chmod(mode)
        temporary.replace(path)
        directory = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        temporary.unlink(missing_ok=True)


def commit_generation_transaction(
    root: Path,
    outputs: Mapping[Path, bytes],
    stale_paths: Sequence[Path],
) -> None:
    """Commit a validated generation set and roll it back on any write error."""

    normalized_outputs: dict[Path, bytes] = {}
    for path, content in outputs.items():
        try:
            path.relative_to(root)
        except ValueError as error:
            raise ValueError(f"generated output escapes repository root: {path}") from error
        normalized_outputs[path] = content
    normalized_stale: set[Path] = set()
    for path in stale_paths:
        try:
            path.relative_to(root)
        except ValueError as error:
            raise ValueError(f"stale generated path escapes repository root: {path}") from error
        if path.is_symlink():
            raise ValueError(f"stale generated path must not be a symlink: {path}")
        if path not in normalized_outputs and path.is_file():
            normalized_stale.add(path)

    targets = set(normalized_outputs) | normalized_stale
    originals: dict[Path, tuple[bytes, int] | None] = {}
    for path in targets:
        if path.is_symlink():
            raise ValueError(f"generated output target must not be a symlink: {path}")
        if path.exists() and not path.is_file():
            raise ValueError(f"generated output target is not a regular file: {path}")
        originals[path] = (
            (path.read_bytes(), path.stat().st_mode & 0o777) if path.is_file() else None
        )

    stage_parent = root / "build/codegen"
    stage_parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=".contract-transaction-",
        dir=stage_parent,
    ) as temporary:
        stage = Path(temporary) / "payload"
        for path, content in sorted(normalized_outputs.items()):
            staged = stage / path.relative_to(root)
            staged.parent.mkdir(parents=True, exist_ok=True)
            staged.write_bytes(content)
            if staged.read_bytes() != content:
                raise RuntimeError(f"staged generation verification failed: {path}")

        committed: list[Path] = []
        try:
            for path in sorted(normalized_stale, reverse=True):
                path.unlink()
                committed.append(path)
            manifest_path = root / GENERATED_MANIFEST
            write_order = sorted(path for path in normalized_outputs if path != manifest_path)
            if manifest_path in normalized_outputs:
                write_order.append(manifest_path)
            for path in write_order:
                content = (stage / path.relative_to(root)).read_bytes()
                committed.append(path)
                atomic_replace_generated_file(path, content)
        except BaseException as error:
            rollback_errors: list[str] = []
            for path in reversed(committed):
                original = originals[path]
                try:
                    if original is None:
                        path.unlink(missing_ok=True)
                    else:
                        atomic_replace_generated_file(path, original[0], original[1])
                except OSError as rollback_error:
                    rollback_errors.append(f"{path}: {rollback_error}")
            if rollback_errors:
                raise RuntimeError(
                    "generation commit failed and rollback was incomplete: "
                    + "; ".join(rollback_errors)
                ) from error
            raise


def nondeterministic_outputs(
    first: Mapping[Path, bytes],
    second: Mapping[Path, bytes],
) -> list[str]:
    """Return every path whose staged bytes differ between two generation passes.

    A path present in exactly one pass differs from the absent side, so an added
    or dropped output is reported alongside a byte-level change.
    """

    return sorted(
        path.as_posix() for path in set(first) | set(second) if first.get(path) != second.get(path)
    )


def generation_pass_projection(
    root: Path,
    outputs: Mapping[Path, bytes],
    descriptor_set: bytes,
) -> dict[Path, bytes]:
    """Key one generation pass by repository-relative path, descriptor included."""

    projection = {path.relative_to(root): content for path, content in outputs.items()}
    projection[Path(DESCRIPTOR_SET_LABEL)] = descriptor_set
    return projection


def require_deterministic_generation(
    root: Path,
    outputs: Mapping[Path, bytes],
    descriptor_set: bytes,
) -> None:
    """Regenerate the complete transaction and require byte-identical output.

    ``protocols/openapi/generation.yaml`` declares deterministic two-pass
    regeneration, so the second pass is mandatory and unconditional: an output
    that depends on wall-clock time, hash iteration order, or plugin state is
    rejected before any file is written and before ``--check`` reports drift.
    """

    second_outputs, second_descriptor_set, _ = generated_outputs(root)
    differences = nondeterministic_outputs(
        generation_pass_projection(root, outputs, descriptor_set),
        generation_pass_projection(root, second_outputs, second_descriptor_set),
    )
    if not differences:
        return
    preview = ", ".join(differences[:20])
    suffix = "" if len(differences) <= 20 else f" (+{len(differences) - 20} more)"
    raise RuntimeError(f"generation is not deterministic: {preview}{suffix}")


def generation_drift(
    root: Path,
    outputs: Mapping[Path, bytes],
    stale_paths: Sequence[Path],
) -> list[Path]:
    """Return deterministic drift without modifying any repository output."""

    drift = [
        path
        for path, content in outputs.items()
        if not path.is_file() or path.read_bytes() != content
    ]
    drift.extend(path for path in stale_paths if path not in outputs and path.is_file())
    return sorted(set(drift))


def require_current_ratification_generation(
    root: Path,
    outputs: Mapping[Path, bytes],
    stale_paths: Sequence[Path],
) -> None:
    """Require ratification to bind the complete reviewed generation transaction."""

    drift = generation_drift(root, outputs, stale_paths)
    if not drift:
        return
    relative = [path.relative_to(root).as_posix() for path in drift]
    preview = ", ".join(relative[:8])
    suffix = "" if len(relative) <= 8 else f" (+{len(relative) - 8} more)"
    raise RuntimeError(
        "ratification requires the complete committed generated estate to be current; "
        f"drift: {preview}{suffix}"
    )


def write_generated(
    root: Path,
    *,
    ratify_v1_baseline: bool,
    expected_candidate_digest: str | None,
    training_vertical_evidence: Path | None,
    training_evidence_signature: Path | None,
    ratification_public_key: Path | None,
    expected_ratification_signer_key_id: str | None,
    ratification_trusted_context: Path | None,
    connected_ratification_signature: Path | None,
    connected_ratification_public_key: Path | None,
    expected_connected_ratification_signer_key_id: str | None,
    check: bool = False,
) -> bool:
    source_digest_before = generation_authority_digest(root)
    outputs, descriptor_set, descriptors = generated_outputs(root)
    require_deterministic_generation(root, outputs, descriptor_set)
    require_conformant_event_registry_projections(event_registry_entries(root, descriptors)[0])
    source_digest_after = generation_authority_digest(root)
    if source_digest_after != source_digest_before:
        raise RuntimeError(
            "contract generation inputs changed during the staged transaction; "
            "no authoritative output was updated"
        )
    predecessor = root / PROTOBUF_PREDECESSOR
    if not predecessor.is_file() or sha256_file(predecessor) != PREDECESSOR_ARTIFACT_DIGEST:
        raise RuntimeError("the archived 22-source Protobuf predecessor is missing or has changed")
    candidate_content = outputs[root / PROTOBUF_CANDIDATE]
    candidate_path = root / PROTOBUF_CANDIDATE
    baseline_path = root / PROTOBUF_RATIFIED_BASELINE
    openapi_baseline_path = root / OPENAPI_CANDIDATE
    ratified_baseline: bytes | None = None
    ratified_openapi: bytes | None = None
    stale_candidates = sorted(
        governed_generated_paths(root)
        | previous_generated_paths(root)
        | discovered_generated_paths(root)
    )
    existing_openapi_baseline = ratified_openapi_document(outputs[openapi_baseline_path])
    if baseline_path.is_file() != (existing_openapi_baseline is not None):
        raise RuntimeError(
            "the Protobuf and OpenAPI v1 baselines must be present or absent together"
        )
    if baseline_path.is_file() and not ratify_v1_baseline:
        baseline = load_json(baseline_path)
        if baseline.get("schema_version") != "mindclade.protobuf-baseline/v3":
            raise RuntimeError("the ratified Protobuf baseline has an unsupported format")
        raw_descriptor = baseline.get("descriptor_set")
        if not isinstance(raw_descriptor, dict):
            raise ValueError("the ratified Protobuf baseline has no descriptor set")
        encoded_descriptor = cast(dict[str, object], raw_descriptor).get("base64")
        if not isinstance(encoded_descriptor, str):
            raise ValueError("the ratified Protobuf baseline has no descriptor bytes")
        with tempfile.NamedTemporaryFile(suffix=".binpb") as previous_file:
            previous_file.write(base64.b64decode(encoded_descriptor, validate=True))
            previous_file.flush()
            run(["buf", "breaking", "--against", previous_file.name], cwd=root)
    if ratify_v1_baseline:
        if baseline_path.exists():
            raise RuntimeError("v1 is already ratified; baseline replacement is prohibited")
        if existing_openapi_baseline is not None:
            raise RuntimeError("v1 OpenAPI is already ratified; baseline replacement is prohibited")
        if not candidate_path.is_file() or candidate_path.read_bytes() != candidate_content:
            raise RuntimeError(
                "ratification requires an up-to-date committed candidate; run ordinary "
                "generation and review it first"
            )
        actual_candidate_digest = sha256_bytes(candidate_content)
        if expected_candidate_digest != actual_candidate_digest:
            raise RuntimeError(
                "ratification requires the exact reviewed candidate artifact digest: "
                f"expected {expected_candidate_digest!r}, actual {actual_candidate_digest!r}"
            )
        require_current_ratification_generation(root, outputs, stale_candidates)
        protected_inputs = {
            "training vertical evidence": training_vertical_evidence,
            "training evidence signature": training_evidence_signature,
            "ratification public key": ratification_public_key,
            "expected ratification signer key ID": expected_ratification_signer_key_id,
            "ratification trusted context": ratification_trusted_context,
            "connected ratification signature": connected_ratification_signature,
            "connected ratification public key": connected_ratification_public_key,
            "expected connected ratification signer key ID": (
                expected_connected_ratification_signer_key_id
            ),
        }
        missing_protected_inputs = sorted(
            name for name, value in protected_inputs.items() if value is None
        )
        if missing_protected_inputs:
            raise RuntimeError(
                "ratification requires explicit protected authorization inputs: "
                + ", ".join(missing_protected_inputs)
            )
        event_entries, _ = event_registry_entries(root, descriptors)
        event_blockers = event_registry_ratification_blockers(event_entries)
        if event_blockers:
            preview = ", ".join(event_blockers[:8])
            suffix = "" if len(event_blockers) <= 8 else f" (+{len(event_blockers) - 8} more)"
            raise RuntimeError(
                "ratification requires every descriptor-visible event to be active with "
                f"producer, semantic consumer, and fixture evidence; blockers: {preview}{suffix}"
            )
        candidate = cast(dict[str, Any], json.loads(candidate_content))
        descriptor_digest = cast(dict[str, str], candidate["descriptor_set"])["digest"]
        event_registry_digest = cast(dict[str, str], candidate["event_registry"])["digest"]
        bindings = ratification_bindings(
            root,
            candidate_descriptor_digest=descriptor_digest,
            event_registry_digest=event_registry_digest,
            staged_outputs=outputs,
        )
        connected_authority = validate_connected_stage5_authority(
            root,
            signature_envelope_path=cast(Path, connected_ratification_signature),
            public_key_path=cast(Path, connected_ratification_public_key),
            expected_signer_key_id=cast(str, expected_connected_ratification_signer_key_id),
        )
        evidence, evidence_digest, authorization = validate_training_vertical_evidence(
            root,
            cast(Path, training_vertical_evidence),
            bindings=bindings,
            signature_envelope_path=cast(Path, training_evidence_signature),
            public_key_path=cast(Path, ratification_public_key),
            expected_signer_key_id=cast(str, expected_ratification_signer_key_id),
            trusted_context_path=cast(Path, ratification_trusted_context),
        )
        authorization.update(connected_authority)
        if authorization["signer_key_id"] == authorization["connected_ratification_signer_key_id"]:
            raise ValueError(
                "training qualification and connected ADR ratification require independent signers"
            )
        ratified_baseline = ratified_protobuf_baseline(
            candidate,
            bindings=bindings,
            evidence=evidence,
            evidence_digest=evidence_digest,
            authorization=authorization,
        )
        ratified_openapi = ratified_openapi_baseline(
            outputs[root / PUBLISHED_OPENAPI],
            descriptor_digest=descriptor_digest,
            bindings=bindings,
            evidence=evidence,
            evidence_digest=evidence_digest,
            authorization=authorization,
        )
    if generation_authority_digest(root) != source_digest_before:
        raise RuntimeError(
            "contract generation inputs changed before commit; no authoritative output was updated"
        )
    if check:
        drift = generation_drift(root, outputs, stale_candidates)
        for path in drift:
            print(path.relative_to(root).as_posix())
        return not drift

    materialized_outputs = dict(outputs)
    if ratified_baseline is not None:
        materialized_outputs[baseline_path] = ratified_baseline
    if ratified_openapi is not None:
        materialized_outputs[openapi_baseline_path] = ratified_openapi
    if ratified_baseline is not None:
        # Revalidate the complete protected transition, including the otherwise
        # absent baseline path, against the generated repository-path authority
        # before any file is committed.
        validate_manifest(root, descriptors, materialized_outputs)
    materialized_outputs.update(
        {
            root / "build/openapi/raw/descriptor-projection.yaml": outputs[
                root / "protocols/openapi/raw/mindclade.openapi.yaml"
            ],
            root / "build/openapi/curated/external-api.yaml": outputs[
                root / "protocols/openapi/curated/mindclade.openapi.yaml"
            ],
            root / "build/openapi/published/external-api.yaml": outputs[
                root / "protocols/openapi/published/mindclade.openapi.yaml"
            ],
        }
    )
    commit_generation_transaction(root, materialized_outputs, stale_candidates)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument(
        "--ratify-v1-baseline",
        action="store_true",
        help="ratify the reviewed candidate after the training vertical evidence gate",
    )
    parser.add_argument(
        "--expected-candidate-digest",
        help="sha256 digest of the exact reviewed candidate artifact",
    )
    parser.add_argument(
        "--training-vertical-evidence",
        type=Path,
        help="signed canonical evidence covering every required training vertical boundary",
    )
    parser.add_argument(
        "--training-evidence-signature",
        type=Path,
        help="detached DSSE envelope signing the exact training evidence bytes",
    )
    parser.add_argument(
        "--ratification-public-key",
        type=Path,
        help="explicit trusted Ed25519 public key for the protected ratification signer",
    )
    parser.add_argument(
        "--expected-ratification-signer-key-id",
        help="sha256 digest of the trusted ratification signer's DER public key",
    )
    parser.add_argument(
        "--ratification-trusted-context",
        type=Path,
        help="canonical trusted protected-pipeline context bound by the signed evidence",
    )
    parser.add_argument(
        "--connected-ratification-signature",
        type=Path,
        help="canonical DSSE envelope for the independently ratified ADR-0015 decision",
    )
    parser.add_argument(
        "--connected-ratification-public-key",
        type=Path,
        help="Ed25519 public key for the connected ADR-0015 ratification signer",
    )
    parser.add_argument(
        "--expected-connected-ratification-signer-key-id",
        help="source-activated DER-SPKI digest for the independent ADR-0015 signer",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the complete atomic generation plan without updating files",
    )
    args = parser.parse_args()
    if args.check and args.ratify_v1_baseline:
        parser.error("--check cannot be combined with --ratify-v1-baseline")
    ratification_inputs = {
        "--expected-candidate-digest": args.expected_candidate_digest,
        "--training-vertical-evidence": args.training_vertical_evidence,
        "--training-evidence-signature": args.training_evidence_signature,
        "--ratification-public-key": args.ratification_public_key,
        "--expected-ratification-signer-key-id": args.expected_ratification_signer_key_id,
        "--ratification-trusted-context": args.ratification_trusted_context,
        "--connected-ratification-signature": args.connected_ratification_signature,
        "--connected-ratification-public-key": args.connected_ratification_public_key,
        "--expected-connected-ratification-signer-key-id": (
            args.expected_connected_ratification_signer_key_id
        ),
    }
    supplied_ratification_inputs = {
        name for name, value in ratification_inputs.items() if value is not None
    }
    if not args.ratify_v1_baseline and supplied_ratification_inputs:
        parser.error(
            "ratification inputs are invalid during ordinary generation: "
            + ", ".join(sorted(supplied_ratification_inputs))
        )
    missing_ratification_inputs = {
        name for name, value in ratification_inputs.items() if value is None
    }
    if args.ratify_v1_baseline and missing_ratification_inputs:
        parser.error(
            "--ratify-v1-baseline requires: " + ", ".join(sorted(missing_ratification_inputs))
        )
    root = args.root.resolve()
    with exclusive_generation_lock(root):
        current = write_generated(
            root,
            ratify_v1_baseline=args.ratify_v1_baseline,
            expected_candidate_digest=args.expected_candidate_digest,
            training_vertical_evidence=(
                args.training_vertical_evidence.resolve()
                if args.training_vertical_evidence is not None
                else None
            ),
            training_evidence_signature=(
                args.training_evidence_signature.resolve()
                if args.training_evidence_signature is not None
                else None
            ),
            ratification_public_key=(
                args.ratification_public_key.resolve()
                if args.ratification_public_key is not None
                else None
            ),
            expected_ratification_signer_key_id=args.expected_ratification_signer_key_id,
            ratification_trusted_context=(
                args.ratification_trusted_context.resolve()
                if args.ratification_trusted_context is not None
                else None
            ),
            connected_ratification_signature=(
                args.connected_ratification_signature.resolve()
                if args.connected_ratification_signature is not None
                else None
            ),
            connected_ratification_public_key=(
                args.connected_ratification_public_key.resolve()
                if args.connected_ratification_public_key is not None
                else None
            ),
            expected_connected_ratification_signer_key_id=(
                args.expected_connected_ratification_signer_key_id
            ),
            check=args.check,
        )
    return 0 if current else 1


if __name__ == "__main__":
    raise SystemExit(main())
