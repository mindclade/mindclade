#!/usr/bin/env python3.12
"""Generate the cross-field constraint validators from one governed table.

Single-field validation belongs to each server validator. This generator owns
only the invariants that relate two or more sibling fields of one request,
because those are the ones no single field's check can hold -- and the ones
that were being hand-copied from service to service until the copies disagreed.

Every message and every field path in `protocols/constraints/cross-field.yaml`
is resolved against the committed candidate descriptor before a line is
emitted, and the file names the descriptor digest it was written against. A
contract change that renames or removes a field therefore breaks generation
loudly rather than leaving five validators checking a field that no longer
exists.

The generator writes formatted text and shells out to no formatter. That is
deliberate: `generate_protocols.py` pins its toolchain by exact version string,
which is right for a pipeline that produces the descriptor, and wrong for one
that produces five small tables. Nothing here needs a toolchain to be
reproducible, so nothing here pins one.
"""

