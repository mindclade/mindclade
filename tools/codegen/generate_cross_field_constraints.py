BANNER = (
    "Code generated by tools/codegen/generate_cross_field_constraints.py. DO NOT EDIT.\n"
    "Source: protocols/constraints/cross-field.yaml\n"
    "Descriptor: {digest}"
)


class GenerationError(RuntimeError):
    """A constraint table that the descriptor does not support."""


@dataclass(frozen=True)
class FieldPath:
    """One resolved dot path, with the presence test its leaf kind implies."""

    path: str
    segments: tuple[str, ...]
    leaf_kind: str  # "message" | "string" | "bytes" | "bool" | "numeric" | "enum"
    repeated: bool


@dataclass(frozen=True)
class Constraint:
    identifier: str
    message: str
    rule: str
    fields: tuple[FieldPath, ...]
    origin: str
    reason: str

    @property
    def sentence(self) -> str:
        return f"{self.identifier}: {RULE_TEXT[self.rule]}"


def load_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise GenerationError(f"expected a JSON object: {path}")
    return cast(dict[str, Any], value)


def index_messages(
    file_set: descriptor_pb2.FileDescriptorSet,
) -> dict[str, descriptor_pb2.DescriptorProto]:
    messages: dict[str, descriptor_pb2.DescriptorProto] = {}

    def walk(prefix: str, nested: Iterable[descriptor_pb2.DescriptorProto]) -> None:
        for message in nested:
            full_name = f"{prefix}.{message.name}"
            messages[full_name] = message
            walk(full_name, message.nested_type)

    for file in file_set.file:
        walk(file.package, file.message_type)
    return messages


def descriptor_bytes(root: Path) -> bytes:
    """Return the committed descriptor, digest-checked against both manifests."""

    candidate = load_json(root / CANDIDATE)
    raw = base64.b64decode(cast(dict[str, Any], candidate["descriptor_set"])["base64"])
    digest = "sha256:" + hashlib.sha256(raw).hexdigest()
    declared = cast(dict[str, Any], candidate["descriptor_set"])["digest"]
    if declared != digest:
        raise GenerationError(
            f"candidate baseline declares {declared} but its bytes digest to {digest}"
        )
    generated = load_json(root / GENERATED_FILES)["descriptor_digest"]
    if generated != digest:
        raise GenerationError(
            f"generated-files manifest declares {generated}, candidate baseline is {digest}"
        )
    return raw


def leaf_kind(field: descriptor_pb2.FieldDescriptorProto) -> str:
    proto = descriptor_pb2.FieldDescriptorProto
    if field.type == TYPE_MESSAGE:
        return "message"
    if field.type == proto.TYPE_STRING:
        return "string"
    if field.type == proto.TYPE_BYTES:
        return "bytes"
    if field.type == proto.TYPE_BOOL:
        return "bool"
    if field.type == proto.TYPE_ENUM:
        return "enum"
    return "numeric"


def resolve_path(
    messages: Mapping[str, descriptor_pb2.DescriptorProto],
    message: str,
    path: str,
    *,
    constraint: str,
) -> FieldPath:
    """Walk one dot path, refusing anything the generated code cannot test."""

    segments = tuple(path.split("."))
    current = message
    field: descriptor_pb2.FieldDescriptorProto | None = None
    for index, segment in enumerate(segments):
        owner = messages.get(current)
        if owner is None:
            raise GenerationError(
                f"{constraint}: {current} is not a message in the descriptor"
                f" (resolving {message}.{path})"
            )
        field = next((candidate for candidate in owner.field if candidate.name == segment), None)
        if field is None:
            raise GenerationError(
                f"{constraint}: {current} has no field {segment!r} (resolving {message}.{path})"
            )
        if field.label == LABEL_REPEATED:
            raise GenerationError(
                f"{constraint}: {message}.{path} traverses repeated field {segment!r};"
                " repeated presence is a length, not a presence test"
            )
        if index < len(segments) - 1:
            if field.type != TYPE_MESSAGE:
                raise GenerationError(
                    f"{constraint}: {message}.{path} descends through non-message field {segment!r}"
                )
            current = field.type_name.lstrip(".")
    assert field is not None
    return FieldPath(
        path=path,
        segments=segments,
        leaf_kind=leaf_kind(field),
        repeated=False,
    )


def load_constraints(root: Path) -> tuple[list[Constraint], str]:
    document = cast(
        dict[str, Any], yaml.safe_load((root / CONSTRAINTS).read_text(encoding="utf-8"))
    )
    schema = load_json(root / CONSTRAINTS_SCHEMA)
    Draft202012Validator.check_schema(schema)
    validator = Draft202012Validator(schema)
    # jsonschema ships no annotations for iter_errors; the elements are
    # ValidationError, and only their `path` and `message` are read below.
    raw_errors: list[Any] = list(validator.iter_errors(document))  # pyright: ignore[reportUnknownMemberType]
    errors = sorted(raw_errors, key=lambda error: list(error.path))
    if errors:
        joined = "\n".join(f"  {list(error.path)}: {error.message}" for error in errors)
        raise GenerationError(f"{CONSTRAINTS} does not satisfy its schema:\n{joined}")

    raw = descriptor_bytes(root)
    file_set = descriptor_pb2.FileDescriptorSet()
    file_set.ParseFromString(raw)
    messages = index_messages(file_set)

    digest = "sha256:" + hashlib.sha256(raw).hexdigest()
    if document["descriptor_digest"] != digest:
        raise GenerationError(
            f"{CONSTRAINTS} was written against {document['descriptor_digest']};"
            f" the committed descriptor is {digest}"
        )

    constraints: list[Constraint] = []
    seen: set[str] = set()
    for entry in cast(Sequence[Mapping[str, Any]], document["constraints"]):
        identifier = str(entry["id"])
        if identifier in seen:
            raise GenerationError(f"duplicate constraint id {identifier!r}")
        seen.add(identifier)
        message = str(entry["message"])
        if message not in messages:
            raise GenerationError(f"{identifier}: {message} is not a message in the descriptor")
        fields = tuple(
            resolve_path(messages, message, str(path), constraint=identifier)
            for path in cast(Sequence[Any], entry["fields"])
        )
        constraints.append(
            Constraint(
                identifier=identifier,
                message=message,
                rule=str(entry["rule"]),
                fields=fields,
                origin=str(entry["origin"]),
                reason=" ".join(str(entry["reason"]).split()),
            )
        )
    constraints.sort(key=lambda constraint: constraint.identifier)
    return constraints, digest


