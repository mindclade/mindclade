def banner_lines(digest: str, prefix: str) -> list[str]:
    return [f"{prefix}{line}".rstrip() for line in BANNER.format(digest=digest).split("\n")]


def render_go(constraints: Sequence[Constraint], digest: str, *, package: str) -> str:
    lines = banner_lines(digest, "// ")
    lines += [
        "",
        f"package {package}",
        "",
        "import (",
        '\t"fmt"',
        '\t"strings"',
        "",
        '\t"google.golang.org/protobuf/proto"',
        '\t"google.golang.org/protobuf/reflect/protoreflect"',
        ")",
        "",
        "// CrossFieldError reports one unsatisfied constraint. The identifier is",
        "// the same string in every language, so an error raised by a facade and an",
        "// error raised by the server name the same rule.",
        "type CrossFieldError struct {",
        "\tConstraint string",
        "\tMessage    string",
        "\tRule       string",
        "\tFields     []string",
        "}",
        "",
        "func (v *CrossFieldError) Error() string {",
        "\treturn fmt.Sprintf(",
        '\t\t"%s: %s on %s: %s",',
        '\t\tv.Constraint, v.Rule, v.Message, strings.Join(v.Fields, ", "),',
        "\t)",
        "}",
        "",
        "type crossFieldRule struct {",
        "\tconstraint string",
        "\tmessage    string",
        "\trule       string",
        "\tfields     [][]string",
        "}",
        "",
        "// crossFieldRules is the generated projection of",
        "// protocols/constraints/cross-field.yaml. Nothing may add to it by hand:",
        "// a rule that exists in one language and not another is the failure this",
        "// table exists to prevent.",
        "var crossFieldRules = []crossFieldRule{",
    ]
    for constraint in constraints:
        lines += [
            "\t{",
            f'\t\tconstraint: "{constraint.identifier}",',
            f'\t\tmessage:    "{constraint.message}",',
            f'\t\trule:       "{constraint.rule}",',
            "\t\tfields: [][]string{",
        ]
        for field in constraint.fields:
            segments = ", ".join(f'"{segment}"' for segment in field.segments)
            lines.append(f"\t\t\t{{{segments}}},")
        lines += ["\t\t},", "\t},"]
    lines += [
        "}",
        "",
        "// fieldIsSet reports proto3 presence: a field is set when it is not its zero",
        "// value. A path that stops at an absent message is unset, not an error --",
        "// an unset parent cannot have a set child.",
        "func fieldIsSet(message proto.Message, path []string) bool {",
        "\tcurrent := message.ProtoReflect()",
        "\tfor index, name := range path {",
        "\t\tdescriptor := current.Descriptor().Fields().ByName(protoreflect.Name(name))",
        "\t\tif descriptor == nil {",
        "\t\t\treturn false",
        "\t\t}",
        "\t\tif index == len(path)-1 {",
        "\t\t\tif current.Has(descriptor) {",
        "\t\t\t\treturn true",
        "\t\t\t}",
        "\t\t\treturn !isZeroScalar(current.Get(descriptor), descriptor)",
        "\t\t}",
        "\t\tif !current.Has(descriptor) {",
        "\t\t\treturn false",
        "\t\t}",
        "\t\tcurrent = current.Get(descriptor).Message()",
        "\t}",
        "\treturn false",
        "}",
        "",
        "func isZeroScalar(",
        "\tvalue protoreflect.Value,",
        "\tdescriptor protoreflect.FieldDescriptor,",
        ") bool {",
        "\tif descriptor.Kind() == protoreflect.MessageKind ||",
        "\t\tdescriptor.Kind() == protoreflect.GroupKind {",
        "\t\treturn true",
        "\t}",
        "\treturn value.Equal(descriptor.Default())",
        "}",
        "",
        "// ValidateCrossField checks every constraint declared for this message type.",
        "// A message with no constraints passes; the caller need not know which types",
        "// carry rules.",
        "func ValidateCrossField(message proto.Message) error {",
        "\tif message == nil {",
        "\t\treturn nil",
        "\t}",
        "\tname := string(message.ProtoReflect().Descriptor().FullName())",
        "\tfor _, rule := range crossFieldRules {",
        "\t\tif rule.message != name {",
        "\t\t\tcontinue",
        "\t\t}",
        "\t\tset := make([]string, 0, len(rule.fields))",
        "\t\tfor _, path := range rule.fields {",
        "\t\t\tif fieldIsSet(message, path) {",
        '\t\t\t\tset = append(set, strings.Join(path, "."))',
        "\t\t\t}",
        "\t\t}",
        "\t\tif violated(rule.rule, len(set), len(rule.fields)) {",
        "\t\t\tfields := set",
        "\t\t\tif len(fields) == 0 {",
        "\t\t\t\tfields = joinedPaths(rule.fields)",
        "\t\t\t}",
        "\t\t\treturn &CrossFieldError{",
        "\t\t\t\tConstraint: rule.constraint,",
        "\t\t\t\tMessage:    rule.message,",
        "\t\t\t\tRule:       rule.rule,",
        "\t\t\t\tFields:     fields,",
        "\t\t\t}",
        "\t\t}",
        "\t}",
        "\treturn nil",
        "}",
        "",
        "func joinedPaths(paths [][]string) []string {",
        "\tjoined := make([]string, 0, len(paths))",
        "\tfor _, path := range paths {",
        '\t\tjoined = append(joined, strings.Join(path, "."))',
        "\t}",
        "\treturn joined",
        "}",
        "",
        "func violated(rule string, set, total int) bool {",
        "\tswitch rule {",
        '\tcase "output-only":',
        "\t\treturn set > 0",
        '\tcase "conflicts-with":',
        "\t\treturn set > 1",
        '\tcase "xor-with":',
        "\t\treturn set != 1",
        '\tcase "required-with":',
        "\t\treturn set != 0 && set != total",
        "\t}",
        "\treturn false",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_python(constraints: Sequence[Constraint], digest: str) -> str:
    lines = [f'"""{BANNER.format(digest=digest)}"""', ""]
    lines += [
        "from __future__ import annotations",
        "",
        "from typing import Any, Final",
        "",
        "",
        "class CrossFieldError(ValueError):",
        '    """One unsatisfied cross-field constraint.',
        "",
        "    ``constraint`` is the same identifier every other language reports, so a",
        "    facade error and a server error name the same rule.",
        '    """',
        "",
        "    def __init__("
        + "self, constraint: str, message: str, rule: str, fields: list[str]"
        + ") -> None:",
        "        super().__init__(f\"{constraint}: {rule} on {message}: {', '.join(fields)}\")",
        "        self.constraint = constraint",
        "        self.message_type = message",
        "        self.rule = rule",
        "        self.fields = fields",
        "",
        "",
        "# The generated projection of protocols/constraints/cross-field.yaml. Nothing",
        "# may add to it by hand: a rule present in one language and absent in another",
        "# is the failure this table exists to prevent.",
        "CrossFieldRule = tuple[str, str, str, tuple[tuple[str, ...], ...]]",
        "",
        "CROSS_FIELD_RULES: Final[tuple[CrossFieldRule, ...]] = (",
    ]
    for constraint in constraints:
        lines += [
            "    (",
            f'        "{constraint.identifier}",',
            f'        "{constraint.message}",',
            f'        "{constraint.rule}",',
            "        (",
        ]
        for field in constraint.fields:
            segments = ", ".join(f'"{segment}"' for segment in field.segments)
            if len(field.segments) == 1:
                segments += ","
            lines.append(f"            ({segments}),")
        lines += ["        ),", "    ),"]
    lines += [
        ")",
        "",
        "",
        "def _is_set(message: Any, path: tuple[str, ...]) -> bool:",
        '    """Proto3 presence: set means "not the zero value".',
        "",
        "    A path that stops at an absent message is unset rather than an error --",
        "    an unset parent cannot have a set child.",
        '    """',
        "",
        "    current: Any = message",
        "    for index, name in enumerate(path):",
        "        descriptor = current.DESCRIPTOR.fields_by_name.get(name)",
        "        if descriptor is None:",
        "            return False",
        "        if index == len(path) - 1:",
        "            if descriptor.message_type is not None:",
        "                return current.HasField(name)",
        "            return bool(getattr(current, name))",
        "        if not current.HasField(name):",
        "            return False",
        "        current = getattr(current, name)",
        "    return False",
        "",
        "",
        "def _violated(rule: str, count: int, total: int) -> bool:",
        '    if rule == "output-only":',
        "        return count > 0",
        '    if rule == "conflicts-with":',
        "        return count > 1",
        '    if rule == "xor-with":',
        "        return count != 1",
        '    if rule == "required-with":',
        "        return count not in (0, total)",
        "    return False",
        "",
        "",
        "def validate_cross_field(message: Any) -> None:",
        '    """Check every constraint declared for this message type.',
        "",
        "    A message with no constraints passes, so the caller need not know which",
        "    types carry rules.",
        '    """',
        "",
        "    if message is None:",
        "        return",
        "    name = message.DESCRIPTOR.full_name",
        "    for constraint, declared, rule, paths in CROSS_FIELD_RULES:",
        "        if declared != name:",
        "            continue",
        "        present = [_join(path) for path in paths if _is_set(message, path)]",
        "        if _violated(rule, len(present), len(paths)):",
        "            raise CrossFieldError(",
        "                constraint, declared, rule, present or [_join(path) for path in paths]",
        "            )",
        "",
        "",
        "def _join(path: tuple[str, ...]) -> str:",
        '    return ".".join(path)',
        "",
    ]
    return "\n".join(lines)


def camel(segment: str) -> str:
    """Field name as protobuf-es emits it.

    The descriptor names fields in snake_case and protobuf-es generates
    camelCase properties, so a TypeScript walker fed descriptor names finds
    nothing at all -- a validator that reports no violation on every message.
    """

    head, *rest = segment.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def render_typescript(constraints: Sequence[Constraint], digest: str) -> str:
    lines = banner_lines(digest, "// ")
    lines += [
        "",
        "/** One unsatisfied cross-field constraint.",
        " *",
        " * `constraint` is the same identifier every other language reports, so a",
        " * facade error and a server error name the same rule.",
        " */",
        "export class CrossFieldError extends Error {",
        "\treadonly constraint: string;",
        "\treadonly messageType: string;",
        "\treadonly rule: string;",
        "\treadonly fields: readonly string[];",
        "",
        "\tconstructor("
        + "constraint: string, messageType: string, "
        + "rule: string, fields: readonly string[]"
        + ") {",
        '\t\tsuper(`${constraint}: ${rule} on ${messageType}: ${fields.join(", ")}`);',
        '\t\tthis.name = "CrossFieldError";',
        "\t\tthis.constraint = constraint;",
        "\t\tthis.messageType = messageType;",
        "\t\tthis.rule = rule;",
        "\t\tthis.fields = fields;",
        "\t}",
        "}",
        "",
        "export interface CrossFieldRule {",
        "\treadonly constraint: string;",
        "\treadonly message: string;",
        "\treadonly rule: string;",
        "\treadonly fields: readonly (readonly string[])[];",
        "}",
        "",
        "// The generated projection of protocols/constraints/cross-field.yaml. Nothing",
        "// may add to it by hand: a rule present in one language and absent in another",
        "// is the failure this table exists to prevent.",
        "//",
        "// Paths are the camelCase names protobuf-es generates, not the snake_case the",
        "// descriptor declares -- a walker fed descriptor names finds nothing and",
        "// reports no violation on every message.",
        "export const CROSS_FIELD_RULES: readonly CrossFieldRule[] = [",
    ]
    for constraint in constraints:
        lines += [
            "\t{",
            f'\t\tconstraint: "{constraint.identifier}",',
            f'\t\tmessage: "{constraint.message}",',
            f'\t\trule: "{constraint.rule}",',
            "\t\tfields: [",
        ]
        for field in constraint.fields:
            segments = ", ".join(f'"{camel(segment)}"' for segment in field.segments)
            lines.append(f"\t\t\t[{segments}],")
        lines += ["\t\t],", "\t},"]
    lines += [
        "];",
        "",
        "// Proto3 presence: set means not the zero value. A path that stops at an",
        "// absent message is unset rather than an error.",
        "function isSet(message: unknown, path: readonly string[]): boolean {",
        "\tlet current: unknown = message;",
        "\tfor (const [index, segment] of path.entries()) {",
        "\t\tif (current === null || current === undefined) {",
        "\t\t\treturn false;",
        "\t\t}",
        '\t\tif (typeof current !== "object") {',
        "\t\t\treturn false;",
        "\t\t}",
        "\t\tconst value = (current as Record<string, unknown>)[segment];",
        "\t\tif (index === path.length - 1) {",
        "\t\t\tif (value === null || value === undefined) return false;",
        '\t\t\tif (typeof value === "string") return value.length > 0;',
        '\t\t\tif (typeof value === "number") return value !== 0;',
        '\t\t\tif (typeof value === "bigint") return value !== 0n;',
        '\t\t\tif (typeof value === "boolean") return value;',
        "\t\t\treturn true;",
        "\t\t}",
        "\t\tcurrent = value;",
        "\t}",
        "\treturn false;",
        "}",
        "",
        "function violated(rule: string, count: number, total: number): boolean {",
        "\tswitch (rule) {",
        '\t\tcase "output-only":',
        "\t\t\treturn count > 0;",
        '\t\tcase "conflicts-with":',
        "\t\t\treturn count > 1;",
        '\t\tcase "xor-with":',
        "\t\t\treturn count !== 1;",
        '\t\tcase "required-with":',
        "\t\t\treturn count !== 0 && count !== total;",
        "\t\tdefault:",
        "\t\t\treturn false;",
        "\t}",
        "}",
        "",
        "/** Check every constraint declared for `messageType`. */",
        "export function validateCrossField("
        + "messageType: string, message: unknown"
        + "): void {",
        "\tfor (const rule of CROSS_FIELD_RULES) {",
        "\t\tif (rule.message !== messageType) continue;",
        "\t\tconst present = rule.fields",
        "\t\t\t.filter((path) => isSet(message, path))",
        '\t\t\t.map((path) => path.join("."));',
        "\t\tif (violated(rule.rule, present.length, rule.fields.length)) {",
        "\t\t\tconst named = present.length > 0 ? present : "
        + 'rule.fields.map((path) => path.join("."));',
        "\t\t\tthrow new CrossFieldError("
        + "rule.constraint, rule.message, rule.rule, named"
        + ");",
        "\t\t}",
        "\t}",
        "}",
        "",
    ]
    return "\n".join(lines)


